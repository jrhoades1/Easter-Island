def next_3gram_site(
    leftover_site: tuple[str, str, int],
) -> tuple[str, str, int]:
    """Next 3-gram starts immediately after leftover 6-gram."""
    side, line, index = leftover_site
    return (side, line, index + STANDING_N6)


def leftover_6gram_site_for_next3(
    site: tuple[str, str, int],
) -> tuple[str, str, int]:
    """Leftover 6-gram starts six tokens before the next-3 start."""
    side, line, index = site
    return (side, line, index - STANDING_N6)


def leftover_6gram_next_3grams(
    i_sides: dict | None = None,
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    leftover_6grams: tuple[tuple[str, ...], ...] | None = None,
) -> tuple[tuple[str, ...] | None, ...]:
    """Per leftover matching leftover-6 remaining site, the next 3-gram or None."""
    if i_sides is None:
        i_sides = load_i_sides()
    if leftover_sites is None:
        leftover_sites = leftover_matching_6gram_sites()
    if leftover_6grams is None:
        leftover_6grams = leftover_remaining_6grams_distinct(i_sides=i_sides)
    out: list[tuple[str, ...] | None] = []
    for site, gram in zip(leftover_sites, leftover_6grams, strict=True):
        side, line, index = site
        stems = i_sides[side][IA_LINE_NAMES.index(line)]
        if tuple(stems[index : index + STANDING_N6]) != gram:
            out.append(None)
            continue
        next_idx = index + STANDING_N6
        if next_idx + 2 < len(stems):
            out.append((stems[next_idx], stems[next_idx + 1], stems[next_idx + 2]))
        else:
            out.append(None)
    return tuple(out)


def leftover_remaining_next3(
    i_sides: dict | None = None,
) -> tuple[tuple[str, ...], ...]:
    """Next 3-grams in leftover-matching leftover-6 remaining site order."""
    return tuple(gram for gram in leftover_6gram_next_3grams(i_sides) if gram is not None)


def leftover_matching_next3_sites(
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    next_3grams: tuple[tuple[str, ...] | None, ...] | None = None,
) -> tuple[tuple[str, str, int], ...]:
    """Leftover matching next-3-gram starts (three tokens after leftover 6-grams)."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_6gram_sites()
    if next_3grams is None:
        next_3grams = leftover_6gram_next_3grams()
    return tuple(
        next_3gram_site(site)
        for site, gram in zip(leftover_sites, next_3grams, strict=True)
        if gram is not None
    )


