def sequence_is_i_only(n_i: int, n_off_i: int) -> bool:
    """True iff N_I>=1 and N_off_I=0."""
    return n_i >= 1 and n_off_i == 0


def sequence_is_hapax_i_only(n_i: int, n_off_i: int) -> bool:
    """True iff hapax on I (N_I=1) and N_off_I=0."""
    return n_i == 1 and n_off_i == 0


def leaking_4grams(
    sequences: tuple[tuple[str, ...], ...],
    n_off_i: tuple[int, ...],
) -> tuple[tuple[str, ...], ...]:
    """Forward 4-grams with N_off_I>0."""
    return tuple(
        gram
        for gram, off in zip(sequences, n_off_i, strict=True)
        if off > 0
    )


def i_leftover_n4_remaining_021_090_076_remaining_after_999_next087_forward_4grams_all_i_only(
    n_population: int,
    n_4grams: int,
    n_line_final: int,
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    per_site_next: tuple[tuple[str, ...] | None, ...],
    expected_n: int = STANDING_N,
    expected_sites: tuple[tuple[str, str, int], ...] = STANDING_SITES,
    sites: tuple[tuple[str, str, int], ...] = STANDING_SITES,
) -> bool:
    """True iff N=3, complete 4-grams, all I-only.

    Loses if any 4-gram appears off I, if N != 3, if a site is
    line-final so the 4-gram set is incomplete relative to N=3,
    or if the three sites no longer compute as the cycle-305
    hapax 600/007/150 trio. Extra I is recorded, not a lose
    condition. Hapax is not assumed; N_I may be greater than 1.
    """
    if sites != expected_sites:
        return False
    if n_population != expected_n:
        return False
    if n_4grams != expected_n:
        return False
    if n_line_final != 0:
        return False
    if any(gram is None for gram in per_site_next):
        return False
    if len(per_site_next) != expected_n:
        return False
    if not n_i or len(n_i) != len(n_off_i):
        return False
    return all(
        sequence_is_i_only(on, off)
        for on, off in zip(n_i, n_off_i, strict=True)
    )


