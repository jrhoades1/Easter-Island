def leftover_remaining_6grams(
    leftovers: tuple[tuple[tuple[str, ...], int, int, tuple], ...] | None = None,
    i_sides: dict | None = None,
) -> tuple[tuple[str, ...], ...]:
    """Leftover-5 remaining plus next AND previous I token at leftover-5 remaining sites."""
    if i_sides is None:
        i_sides = load_i_sides()
    out: list[tuple[str, ...]] = []
    for side, line, index in leftover_matching_5gram_sites(leftovers):
        stems = i_sides[side][IA_LINE_NAMES.index(line)]
        out.append(tuple(stems[index : index + STANDING_N6]))
        out.append(tuple(stems[index - 1 : index + STANDING_N5]))
    return tuple(out)


def leftover_remaining_6grams_distinct(
    leftovers: tuple[tuple[tuple[str, ...], int, int, tuple], ...] | None = None,
    i_sides: dict | None = None,
) -> tuple[tuple[str, ...], ...]:
    """First-seen leftover remaining 6-grams (shared adjacent listings collapsed)."""
    seen: set[tuple[str, ...]] = set()
    out: list[tuple[str, ...]] = []
    for gram in leftover_remaining_6grams(leftovers, i_sides):
        if gram not in seen:
            seen.add(gram)
            out.append(gram)
    return tuple(out)


def leftover_matching_6gram_listing_sites(
    leftovers: tuple[tuple[tuple[str, ...], int, int, tuple], ...] | None = None,
) -> tuple[tuple[str, str, int], ...]:
    """Leftover matching leftover-6 listing sites: leftover-5 index and index-1."""
    out: list[tuple[str, str, int]] = []
    for side, line, index in leftover_matching_5gram_sites(leftovers):
        out.append((side, line, index))
        out.append((side, line, index - 1))
    return tuple(out)


def leftover_matching_6gram_sites(
    leftovers: tuple[tuple[tuple[str, ...], int, int, tuple], ...] | None = None,
) -> tuple[tuple[str, str, int], ...]:
    """Leftover matching leftover-6 remaining sites (distinct, first-seen)."""
    seen: set[tuple[str, str, int]] = set()
    out: list[tuple[str, str, int]] = []
    for site in leftover_matching_6gram_listing_sites(leftovers):
        if site not in seen:
            seen.add(site)
            out.append(site)
    return tuple(out)


def leftover_6gram_extension_flags(
    leftovers: tuple[tuple[tuple[str, ...], int, int, tuple], ...] | None = None,
    i_sides: dict | None = None,
) -> tuple[int, int, int, int]:
    """N_no_next1, N_line_final, N_no_prev1, N_line_initial at leftover-5 remaining sites."""
    if i_sides is None:
        i_sides = load_i_sides()
    n_no_next1 = 0
    n_line_final = 0
    n_no_prev1 = 0
    n_line_initial = 0
    for side, line, index in leftover_matching_5gram_sites(leftovers):
        stems = i_sides[side][IA_LINE_NAMES.index(line)]
        nlen = len(stems)
        if index + STANDING_N6 > nlen:
            n_no_next1 += 1
        if index + STANDING_N5 >= nlen:
            n_line_final += 1
        if index < 1 or index + STANDING_N5 > nlen:
            n_no_prev1 += 1
        if index == 0:
            n_line_initial += 1
    return n_no_next1, n_line_final, n_no_prev1, n_line_initial


def leftover_6gram_complete_set(
    leftovers: tuple[tuple[tuple[str, ...], int, int, tuple], ...] | None = None,
    i_sides: dict | None = None,
) -> bool:
    """True iff every leftover-5 remaining site supports both next and previous."""
    n_no_next1, n_line_final, n_no_prev1, n_line_initial = leftover_6gram_extension_flags(
        leftovers, i_sides
    )
    return (
        n_no_next1 == 0
        and n_line_final == 0
        and n_no_prev1 == 0
        and n_line_initial == 0
    )


def leftover_matching_subset(
    leftover_sites: tuple[tuple[str, str, int], ...] = STANDING_LEFTOVER_MATCHING_SITES,
    i_sites: tuple[tuple[tuple[str, str, int], ...], ...] = STANDING_I_SITES,
) -> bool:
    """True iff leftover matching leftover-6 remaining sites equal the union of I sites."""
    measured = set(site for sites in i_sites for site in sites)
    return set(leftover_sites) == measured


def extra_i_sites_of_6gram(
    i_sites: tuple[tuple[str, str, int], ...],
    leftover_matching: tuple[tuple[str, str, int], ...] = STANDING_LEFTOVER_MATCHING_SITES,
) -> tuple[tuple[str, str, int], ...]:
    """I 6-gram sites outside leftover matching leftover-6 remaining sites."""
    leftover_set = set(leftover_matching)
    return tuple(site for site in i_sites if site not in leftover_set)


def sequence_is_i_only(n_i: int, n_off_i: int) -> bool:
    """True iff N_I>=1 and N_off_I=0."""
    return n_i >= 1 and n_off_i == 0


def leaking_6grams(
    sequences: tuple[tuple[str, ...], ...],
    n_off_i: tuple[int, ...],
) -> tuple[tuple[str, ...], ...]:
    """Distinct leftover 6-grams with N_off_I>0."""
    return tuple(
        gram
        for gram, off in zip(sequences, n_off_i, strict=True)
        if off > 0
    )


def leftover_n4_leftover6_overlap_sites(
    leftovers: tuple[tuple[tuple[str, ...], int, int, tuple], ...] | None = None,
) -> tuple[tuple[str, str, int], ...]:
    """Leftover-4 remaining sites that are also leftover matching leftover-6 sites."""
    leftover4 = set(leftover_matching_leftover4_of_leftover5(leftovers))
    leftover6 = set(leftover_matching_6gram_sites(leftovers))
    return tuple(site for site in leftover_matching_leftover4_of_leftover5(leftovers) if site in leftover6)


def i_leftover_n6_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    sequences: tuple[tuple[str, ...], ...] = STANDING_SEQUENCES,
    expected_n: int = STANDING_N,
    leftovers: tuple[tuple[tuple[str, ...], int, int, tuple], ...] | None = None,
    i_sides: dict | None = None,
) -> bool:
    """True iff leftover remaining-after-076-010 leftover 6-grams are I-only and complete.

    Claim holds only if leftover-5 remaining plus next AND previous still
    yields those leftover 6-grams, every leftover-5 remaining site supports
    both extensions, and every leftover 6-gram has N_I>=1 and N_off_I=0.
    Hapax is not assumed. Nested leftover-2 peels stay nested. Extra I of
    leftover 6-grams is recorded, not this claim.
    """
    listings = leftover_remaining_6grams(leftovers, i_sides)
    distinct = leftover_remaining_6grams_distinct(leftovers, i_sides)
    return (
        listings == STANDING_LISTINGS
        and distinct == sequences
        and leftover_6gram_complete_set(leftovers, i_sides)
        and all(len(gram) == STANDING_N6 for gram in listings)
        and len(n_i) == expected_n
        and len(n_off_i) == expected_n
        and all(
            sequence_is_i_only(on, off)
            for on, off in zip(n_i, n_off_i, strict=True)
        )
    )


