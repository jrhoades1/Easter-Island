    """True iff extra I=2, complete previous 4-grams, all I-only.

    Hapax is not required. Loses if any extra-I 4-gram appears
    off I, if extra_I_total != 2, if an extra-I site is
    line-initial so the 4-gram set is incomplete relative to
    extra_I_total=2, if extra I of I-only previous 3-grams with
    extra I no longer computes, or if previous 3-grams no longer
    compute. Leftover matching leftover-3 / leftover-2 /
    previous-4 / previous-3 / previous-2 of leftover 4-grams
    stay nested and do not make the claim lose. Leftover
    matching extra-I previous-2-gram 4-grams (cycle 409 / 410)
    are recorded, not skipped, and do not make the claim lose.
    Extra I of leftover matching leftover-3 / previous-4 /
    previous-3 / previous-2 is not this cycle's claim.
    Incomplete-set is LOSE. Any N_leak>0 is LOSE. Extra I of
    the 4-grams ≠ 0 does not make the claim lose.
    """
    if not leftover_prev3_still:
        return False
    if n_extra_total != expected_n_extra:
        return False
    if extra_sites != expected_extra_sites:
        return False
    if any(gram is None for gram, _site, _role, _parent in rows):
        return False
    if len(grams) != expected_n or len(n_i) != expected_n or len(n_off_i) != expected_n:
        return False
    if any(gram in CYCLE340_SEQUENCES for gram in grams):
        return False
    if not all(
        sequence_is_i_only(on, off)
        for on, off in zip(n_i, n_off_i, strict=True)
    ):
        return False
    return len(rows) == expected_n_extra


