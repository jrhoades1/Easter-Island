def site_next_4gram_for_2gram(
    stems: list[str],
    index: int,
    gram2: tuple[str, ...],
) -> tuple[str, ...] | None:
    """X Y Z W if two next stems exist; None at line-final or mismatch."""
    if tuple(stems[index : index + len(gram2)]) != gram2:
        return None
    if index + len(gram2) + 1 >= len(stems):
        return None
    return tuple(stems[index : index + len(gram2) + 2])


def extra_i_2gram_4grams_at_sites(
    i_sides: dict[str, list[list[str]]],
    extra_sites: tuple[tuple[str, str, int], ...],
    parent_2grams: tuple[tuple[str, ...], ...],
    leftover_matching_2gram_starts: tuple[tuple[str, str, int], ...] | None = None,
) -> tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...]:
    """Leftover 2-gram plus next two tokens at extra I sites; leftover matching 4-grams excluded."""
    if leftover_matching_2gram_starts is None:
        leftover_matching_2gram_starts = tuple(
            site for row in CYCLE349_MATCHING_EACH for site in row
        )
    leftover_2_starts = set(leftover_matching_2gram_starts)
    leftover_4_set = set(CYCLE340_SEQUENCES)
    out: list[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]]] = []
    for site, gram2 in zip(extra_sites, parent_2grams, strict=True):
        if site in leftover_2_starts:
            continue
        stems = line_stems_for_site(i_sides, site)
        next4 = site_next_4gram_for_2gram(stems, site[2], gram2)
        if next4 is None:
            continue
        if next4 in leftover_4_set:
            continue
        out.append((next4, site, "next", gram2))
    return tuple(out)


def distinct_extra_i_4grams(
    rows: tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...],
) -> tuple[tuple[str, ...], ...]:
    """First-seen distinct extra-I leftover-2-gram 4-grams."""
    seen_grams: list[tuple[str, ...]] = []
    for gram, _site, _role, _parent in rows:
        if gram not in seen_grams:
            seen_grams.append(gram)
    return tuple(seen_grams)


