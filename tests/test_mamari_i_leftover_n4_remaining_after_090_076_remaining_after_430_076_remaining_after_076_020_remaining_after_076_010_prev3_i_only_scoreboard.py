def previous_3gram_start_site(
    leftover_site: tuple[str, str, int],
) -> tuple[str, str, int] | None:
    """Previous 3-gram starts one token before leftover 4-gram."""
    side, line, index = leftover_site
    if index < 1:
        return None
    return (side, line, index - 1)


def leftover_4gram_site_for_prev3(
    site: tuple[str, str, int],
) -> tuple[str, str, int]:
    """Leftover 4-gram starts one token after the previous-3 start."""
    side, line, index = site
    return (side, line, index + 1)


def extra_i_sites_of_3gram(
    i_sites: tuple[tuple[str, str, int], ...],
    leftover_matching: tuple[tuple[str, str, int], ...] = STANDING_LEFTOVER_MATCHING_SITES,
) -> tuple[tuple[str, str, int], ...]:
    """I 3-gram starts whose leftover 4-gram start is outside leftover matching sites."""
    leftover_set = set(leftover_matching)
    return tuple(
        site
        for site in i_sites
        if leftover_4gram_site_for_prev3(site) not in leftover_set
    )


def leftover_matching_equals_prev3_plus_one(
    leftover_sites: tuple[tuple[str, str, int], ...] = STANDING_LEFTOVER_MATCHING_SITES,
    matching_prev3_sites: tuple[tuple[str, str, int], ...] = STANDING_LEFTOVER_MATCHING_PREV3_SITES,
) -> bool:
    """True iff leftover matching 4-gram sites equal leftover-matching previous-3 starts plus one."""
    measured = set(leftover_4gram_site_for_prev3(site) for site in matching_prev3_sites)
    return set(leftover_sites) == measured


def sequence_is_i_only(n_i: int, n_off_i: int) -> bool:
    """True iff N_I>=1 and N_off_I=0."""
    return n_i >= 1 and n_off_i == 0


def sequence_is_hapax_i_only(n_i: int, n_off_i: int) -> bool:
    """True iff hapax on I (N_I=1) and N_off_I=0."""
    return n_i == 1 and n_off_i == 0


def leaking_3grams(
    sequences: tuple[tuple[str, ...], ...],
    n_off_i: tuple[int, ...],
) -> tuple[tuple[str, ...], ...]:
    """Distinct leftover previous 3-grams with N_off_I>0."""
    return tuple(
        gram
        for gram, off in zip(sequences, n_off_i, strict=True)
        if off > 0
    )


def i_leftover_n4_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_previous_3grams_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    sequences: tuple[tuple[str, ...], ...] = STANDING_SEQUENCES,
    expected_n: int = STANDING_N,
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    previous_3grams: tuple[tuple[str, ...] | None, ...] | None = None,
    leftovers: tuple[tuple[tuple[str, ...], int, int, tuple], ...] | None = None,
) -> bool:
    """True iff all 11 leftover remaining-after-076-010 previous 3-grams are I-only.

    Claim holds only if leftover matching sites still compute as
    those 11, every leftover matching site has a previous token so
    the 3-gram set is complete relative to N=11, the five leftover
    4-grams still compute, and every previous 3-gram has N_I>=1
    and N_off_I=0. Hapax is not assumed. Nested cycle 346 prev5
    I-only, cycle 345 unique-max lose, leftover 3-gram I-only,
    and leftover 4-gram I-only do not make this claim lose.
    Peeling labeled G is not this claim. Extra I is recorded, not
    a lose condition.
    """
    if leftovers is None:
        leftovers = leftover_n4_rows()
    remaining_grams = leftover_remaining_grams(leftovers)
    if leftover_sites is None:
        leftover_sites = leftover_matching_4gram_sites()
    if previous_3grams is None:
        previous_3grams = leftover_4gram_previous_3grams(load_i_sides())
    return (
        remaining_grams == STANDING_LEFTOVER_4GRAMS
        and leftover_sites == STANDING_LEFTOVER_MATCHING_SITES
        and len(leftover_sites) == expected_n
        and len(previous_3grams) == expected_n
        and None not in previous_3grams
        and tuple(previous_3grams) == sequences
        and len(n_i) == expected_n
        and len(n_off_i) == expected_n
        and all(
            sequence_is_i_only(on, off)
            for on, off in zip(n_i, n_off_i, strict=True)
        )
    )


