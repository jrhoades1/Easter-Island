def site_next_5gram_for_4gram(
    stems: list[str],
    index: int,
    gram4: tuple[str, ...],
) -> tuple[str, ...] | None:
    """X Y Z W V if the next token exists; None at line-final or mismatch."""
    if tuple(stems[index : index + len(gram4)]) != gram4:
        return None
    if index + len(gram4) >= len(stems):
        return None
    return tuple(stems[index : index + len(gram4) + 1])


def leftover_matching_next5_sites(
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    i_sides: dict[str, list[list[str]]] | None = None,
) -> tuple[tuple[str, str, int], ...]:
    """Leftover matching next-4 starts that have a next token (nested next-5)."""
