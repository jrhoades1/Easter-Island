def previous_6gram_site(
    leftover_site: tuple[str, str, int],
) -> tuple[str, str, int] | None:
    """Previous 6-gram starts six tokens before leftover 5-gram."""
    side, line, index = leftover_site
    if index < STANDING_N6:
        return None
    return (side, line, index - STANDING_N6)


def leftover_5gram_site_for_prev6(
    site: tuple[str, str, int],
) -> tuple[str, str, int]:
    """Leftover 5-gram starts six tokens after the previous-6 start."""
    side, line, index = site
    return (side, line, index + STANDING_N6)


def leftover_5gram_previous_6grams(
    i_sides: dict | None = None,
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    leftover_5grams: tuple[tuple[str, ...], ...] | None = None,
) -> tuple[tuple[str, ...] | None, ...]:
    """Per leftover matching leftover-5 remaining site, the previous 6-gram or None."""
    if i_sides is None:
        i_sides = load_i_sides()
    if leftover_sites is None:
        leftover_sites = leftover_matching_5gram_sites()
    if leftover_5grams is None:
        leftover_5grams = leftover_remaining_5grams(i_sides=i_sides)
    out: list[tuple[str, ...] | None] = []
    for site, gram in zip(leftover_sites, leftover_5grams, strict=True):
        side, line, index = site
        stems = i_sides[side][IA_LINE_NAMES.index(line)]
        if tuple(stems[index : index + STANDING_N5]) != gram:
            out.append(None)
            continue
        if index >= STANDING_N6:
            out.append(tuple(stems[index - STANDING_N6 : index]))
        else:
            out.append(None)
    return tuple(out)


def leftover_remaining_prev6(
    i_sides: dict | None = None,
) -> tuple[tuple[str, ...], ...]:
    """Previous 6-grams that exist (drops None)."""
    return tuple(gram for gram in leftover_5gram_previous_6grams(i_sides) if gram is not None)


def leftover_matching_prev6_sites(
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    previous_6grams: tuple[tuple[str, ...] | None, ...] | None = None,
) -> tuple[tuple[str, str, int], ...]:
    """Leftover matching previous-4-gram starts (sites that have six preceding tokens)."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_5gram_sites()
    if previous_6grams is None:
        previous_6grams = leftover_5gram_previous_6grams()
    return tuple(
        previous_6gram_site(site)
        for site, gram in zip(leftover_sites, previous_6grams, strict=True)
        if gram is not None
    )


def leftover_matching_prev6_sites_each(
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    sequences: tuple[tuple[str, ...], ...] = STANDING_SEQUENCES,
) -> tuple[tuple[tuple[str, str, int], ...], ...]:
    """Per previous 6-gram leftover matching previous-4-gram sites."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_5gram_sites()
    previous_6grams = leftover_5gram_previous_6grams()
    prev_sites = leftover_matching_prev6_sites(leftover_sites, previous_6grams)
    buckets: dict[tuple[str, ...], list[tuple[str, str, int]]] = {
        gram: [] for gram in sequences
    }
    for gram, site in zip(
        (g for g in previous_6grams if g is not None),
        prev_sites,
        strict=True,
    ):
        buckets[gram].append(site)
    return tuple(tuple(buckets[gram]) for gram in sequences)


