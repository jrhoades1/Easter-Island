def i_leftover_n4_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_previous_3grams_tokens_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    sequences: tuple[tuple[str, ...], ...] = STANDING_SEQUENCES,
    expected_n: int = STANDING_N,
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    previous_3grams: tuple[tuple[str, ...] | None, ...] | None = None,
    leftovers: tuple[tuple[tuple[str, ...], int, int, tuple], ...] | None = None,
) -> bool:
    """True iff all leftover remaining-after-076-010 previous 3-grams are I-only.

    Claim holds only if leftover matching sites still compute as
    those 11, every leftover matching site has three previous tokens
    so the 3-gram set is complete relative to N=11, the five leftover
    4-grams still compute, and every previous 3-gram has N_I>=1 and
    N_off_I=0. Extra I does not make the claim lose. Incomplete set
    is LOSE. Leak is I-only LOSE. Nested leftover 4-gram / previous
    2-gram leak / previous 4-gram incomplete-set / extra-I previous-2
    peels do not make this claim lose.
    """
    if leftovers is None:
        leftovers = leftover_n4_rows()
    remaining_grams = leftover_remaining_grams(leftovers)
    if leftover_sites is None:
        leftover_sites = leftover_matching_4gram_sites()
    if previous_3grams is None:
        previous_3grams = leftover_4gram_previous_3grams_tokens()
    existing = tuple(gram for gram in previous_3grams if gram is not None)
    return (
        remaining_grams == CYCLE340_SEQUENCES
        and leftover_sites == STANDING_LEFTOVER_MATCHING_4GRAM_SITES
        and len(leftover_sites) == expected_n
        and None not in previous_3grams
        and len(previous_3grams) == expected_n
        and existing == sequences
        and len(n_i) == expected_n
        and len(n_off_i) == expected_n
        and all(
            sequence_is_i_only(on, off)
            for on, off in zip(n_i, n_off_i, strict=True)
        )
    )


