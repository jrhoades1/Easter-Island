def previous_3gram_site(
    leftover_site: tuple[str, str, int],
) -> tuple[str, str, int] | None:
    """Previous 3-gram starts three tokens before leftover 4-gram."""
    side, line, index = leftover_site
    if index < 3:
        return None
    return (side, line, index - 3)


def leftover_4gram_site_for_prev3(
    site: tuple[str, str, int],
) -> tuple[str, str, int]:
    """Leftover 4-gram starts three tokens after the previous-3 start."""
    side, line, index = site
    return (side, line, index + 3)


def site_previous_3gram_tokens_before_4gram(
    stems: list[str],
    index: int,
    gram4: tuple[str, ...],
) -> tuple[str, ...] | None:
    """Three tokens before leftover 4-gram; None if fewer than three precede."""
    if tuple(stems[index : index + len(gram4)]) != gram4:
        return None
    if index < 3:
        return None
    return tuple(stems[index - 3 : index])


def leftover_4gram_previous_3grams_tokens(
    i_sides: dict[str, list[list[str]]] | None = None,
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    grams4: tuple[tuple[str, ...], ...] = CYCLE340_MATCHING_4GRAMS,
) -> tuple[tuple[str, ...] | None, ...]:
    """Previous 3-grams (three tokens before) in leftover-matching-site order."""
    if i_sides is None:
        i_sides = load_i_sides()
    if leftover_sites is None:
        leftover_sites = leftover_matching_4gram_sites()
    return tuple(
        site_previous_3gram_tokens_before_4gram(
            line_stems_for_site(i_sides, site), site[2], gram
        )
        for site, gram in zip(leftover_sites, grams4, strict=True)
    )


def leftover_remaining_prev3_tokens(
    i_sides: dict[str, list[list[str]]] | None = None,
) -> tuple[tuple[str, ...], ...]:
    """Previous 3-grams that exist (drops None)."""
    return tuple(
        gram for gram in leftover_4gram_previous_3grams_tokens(i_sides) if gram is not None
    )


def leftover_matching_prev3_sites(
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    previous_3grams: tuple[tuple[str, ...] | None, ...] | None = None,
) -> tuple[tuple[str, str, int], ...]:
    """Leftover matching previous-3-gram starts (sites that have three preceding tokens)."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_4gram_sites()
    if previous_3grams is None:
        previous_3grams = leftover_4gram_previous_3grams_tokens()
    return tuple(
        previous_3gram_site(site)
        for site, gram in zip(leftover_sites, previous_3grams, strict=True)
        if gram is not None
    )


def leftover_matching_prev3_sites_each(
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    sequences: tuple[tuple[str, ...], ...] = STANDING_SEQUENCES,
) -> tuple[tuple[tuple[str, str, int], ...], ...]:
    """Per previous 3-gram leftover matching previous-3-gram sites."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_4gram_sites()
    previous_3grams = leftover_4gram_previous_3grams_tokens()
    prev_sites = leftover_matching_prev3_sites(leftover_sites, previous_3grams)
    buckets: dict[tuple[str, ...], list[tuple[str, str, int]]] = {
        gram: [] for gram in sequences
    }
    for gram, site in zip(
        (g for g in previous_3grams if g is not None),
        prev_sites,
        strict=True,
    ):
        buckets[gram].append(site)
    return tuple(tuple(buckets[gram]) for gram in sequences)


