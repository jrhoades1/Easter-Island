def i_leftover_n4_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_extra_i_1gram_4grams_all_i_only(
    n_i,
    n_off_i,
    extra_sites,
    rows,
    grams,
    n_extra_total,
    leftover_1grams_still,
    expected_extra_sites=STANDING_EXTRA_I_SITES_FLAT,
    expected_n_extra=STANDING_N_EXTRA_I,
    expected_n=STANDING_N_DISTINCT_4GRAMS,
):
    """True iff extra I=93, complete next 4-grams, all I-only.

    Hapax is not required. Loses if any extra-I 4-gram appears
    off I, if extra_I_total != 93, if an extra-I site is
    line-final / 1-from-end / 2-from-end so the 4-gram set is
    empty relative to extra_I_total=93, if extra I of I-only
    leftover 1-grams with extra I no longer computes, or if
    leftover 1-grams no longer compute. Leftover matching
    leftover-4-grams of leftover 4-grams stay nested and do
    not make the claim lose. Extra I of leftover matching
    leftover-4-grams is not this cycle's claim.
    """
    if not leftover_1grams_still:
        return False
    if n_extra_total != expected_n_extra:
        return False
    if extra_sites != expected_extra_sites:
        return False
    if any(gram is None for gram, _site, _role, _parent in rows):
        return False
    if len(grams) != expected_n or len(n_i) != expected_n or len(n_off_i) != expected_n:
        return False
    if any(gram in CYCLE340_SEQUENCES for gram in grams):
        return False
    if not all(
        sequence_is_i_only(on, off)
        for on, off in zip(n_i, n_off_i, strict=True)
    ):
        return False
    return len(rows) == expected_n_extra


