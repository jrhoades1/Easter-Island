def i_leftover_n4_remaining_021_090_076_remaining_after_999_previous_3grams_all_i_only(
    n_population: int,
    n_3grams: int,
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    per_site_previous: tuple[tuple[str, ...] | None, ...],
    expected_n: int = STANDING_N,
    expected_sites: tuple[tuple[str, str, int], ...] = STANDING_SITES,
    sites: tuple[tuple[str, str, int], ...] = STANDING_SITES,
) -> bool:
    """True iff N=3, complete 3-grams, all I-only.

    Loses if any 3-gram appears off I, if N != 3, or if the
    three sites no longer compute as the cycle-305 hapax
    600/007/150 trio. Extra I is recorded, not a lose
    condition. Hapax is not assumed; N_I may be greater than 1.
    """
    if sites != expected_sites:
        return False
    if n_population != expected_n:
        return False
    if n_3grams != expected_n:
        return False
    if any(gram is None for gram in per_site_previous):
        return False
    if len(per_site_previous) != expected_n:
        return False
    if not n_i or len(n_i) != len(n_off_i):
        return False
    return all(
        sequence_is_i_only(on, off)
        for on, off in zip(n_i, n_off_i, strict=True)
    )


