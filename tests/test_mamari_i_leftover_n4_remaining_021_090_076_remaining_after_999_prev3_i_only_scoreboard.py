def previous_3gram_start_site(
    leftover_site: tuple[str, str, int],
) -> tuple[str, str, int] | None:
    """Previous 3-gram starts two tokens before leftover 090 076."""
    side, line, index = leftover_site
    if index < 2:
        return None
    return (side, line, index - 2)


def leftover_n4_remaining_090_076_site_for_3gram(
    site: tuple[str, str, int],
) -> tuple[str, str, int]:
    """090 076 starts two tokens after the previous-3 start."""
    side, line, index = site
    return (side, line, index + 2)


def extra_i_sites_of_3gram(
    i_sites: tuple[tuple[str, str, int], ...],
    leftover_trio: tuple[tuple[str, str, int], ...] = STANDING_SITES,
) -> tuple[tuple[str, str, int], ...]:
    """I 3-gram starts whose leftover 090-start is outside the N=3 trio."""
    leftover_set = set(leftover_trio)
    return tuple(
        site
        for site in i_sites
        if leftover_n4_remaining_090_076_site_for_3gram(site) not in leftover_set
    )


def sequence_is_i_only(n_i: int, n_off_i: int) -> bool:
    """True iff N_I>=1 and N_off_I=0."""
    return n_i >= 1 and n_off_i == 0


def sequence_is_hapax_i_only(n_i: int, n_off_i: int) -> bool:
    """True iff hapax on I (N_I=1) and N_off_I=0."""
    return n_i == 1 and n_off_i == 0


def leaking_3grams(
    sequences: tuple[tuple[str, ...], ...],
    n_off_i: tuple[int, ...],
) -> tuple[tuple[str, ...], ...]:
    """Previous 3-grams with N_off_I>0."""
    return tuple(
        gram
        for gram, off in zip(sequences, n_off_i, strict=True)
        if off > 0
    )


def site_previous_3gram_drop_076(
    stems: list[str],
    index: int,
    allowed_4grams: tuple[tuple[str, ...], ...] = LOCKED_HAPAX_PREVIOUS_4GRAMS,
    gram2: tuple[str, ...] = GRAM2,
) -> tuple[str, ...] | None:
    """Hapax previous 4-gram with trailing 076 dropped; None if missing."""
    prev4 = site_previous_4gram(stems, index, gram2)
    if prev4 is None or prev4 not in allowed_4grams:
        return None
    return prev4[:-1]


