def previous_1gram_site(
    leftover_site: tuple[str, str, int],
) -> tuple[str, str, int] | None:
    """Previous 1-gram is the token immediately before leftover 4-gram."""
    return previous_2gram_start_site(leftover_site)


def leftover_4gram_site_for_prev1(
    site: tuple[str, str, int],
) -> tuple[str, str, int]:
    """Leftover 4-gram starts one token after the previous-1 site."""
    side, line, index = site
    return (side, line, index + 1)


def leftover_remaining_prev1(
    i_sides: dict[str, list[list[str]]] | None = None,
) -> tuple[tuple[str, ...], ...]:
    """Previous 1-grams in leftover-matching-site order."""
    if i_sides is None:
        i_sides = load_i_sides()
    stems = leftover_4gram_previous_stems(i_sides)
    return tuple((stem,) for stem in stems if stem is not None)


def leftover_matching_prev1_sites(
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
) -> tuple[tuple[str, str, int], ...]:
    """Leftover matching previous-1-gram sites (one token before leftover 4-grams)."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_4gram_sites()
    sites = []
    for leftover_site in leftover_sites:
        prev = previous_1gram_site(leftover_site)
        if prev is not None:
            sites.append(prev)
    return tuple(sites)


def leftover_matching_prev1_sites_each(
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    sequences: tuple[tuple[str, ...], ...] = STANDING_SEQUENCES,
) -> tuple[tuple[tuple[str, str, int], ...], ...]:
    """Per previous 1-gram leftover matching previous-1-gram sites."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_4gram_sites()
    prev_sites = leftover_matching_prev1_sites(leftover_sites)
    i_sides = load_i_sides()
    stems = leftover_4gram_previous_stems(i_sides)
    buckets: dict[str, list[tuple[str, str, int]]] = {tok[0]: [] for tok in sequences}
    for stem, site in zip(stems, prev_sites, strict=True):
        if stem is None:
            continue
        buckets[stem].append(site)
    return tuple(tuple(buckets[tok[0]]) for tok in sequences)


def extra_i_sites_of_1gram(
    i_sites: tuple[tuple[str, str, int], ...],
    leftover_matching: tuple[tuple[str, str, int], ...],
) -> tuple[tuple[str, str, int], ...]:
    """I 1-gram sites outside leftover matching previous-1-gram sites."""
    leftover_set = set(leftover_matching)
    return tuple(site for site in i_sites if site not in leftover_set)


def leftover_matching_equals_prev1_plus_one(
    leftover_sites: tuple[tuple[str, str, int], ...] = STANDING_LEFTOVER_MATCHING_4GRAM_SITES,
    matching_prev1_sites: tuple[tuple[str, str, int], ...] = STANDING_LEFTOVER_MATCHING_PREV1_SITES,
) -> bool:
    """True iff leftover matching 4-gram sites equal previous-1 starts plus one."""
    measured = set(leftover_4gram_site_for_prev1(site) for site in matching_prev1_sites)
    return set(leftover_sites) == measured


def sequence_is_i_only(n_i: int, n_off_i: int) -> bool:
    """True iff N_I>=1 and N_off_I=0."""
    return n_i >= 1 and n_off_i == 0


def sequence_is_hapax(n_i: int, n_off_i: int) -> bool:
    """True iff N_I==1 and N_off_I=0."""
    return n_i == 1 and n_off_i == 0


def leaking_1grams(
    sequences: tuple[tuple[str, ...], ...],
    n_off_i: tuple[int, ...],
) -> tuple[tuple[str, ...], ...]:
    """Previous 1-grams with N_off_I>0."""
    return tuple(
        gram
        for gram, off in zip(sequences, n_off_i, strict=True)
        if off > 0
    )


