def i_leftover_n4_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_previous_1grams_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    sequences: tuple[tuple[str, ...], ...] = STANDING_SEQUENCES,
    expected_n: int = STANDING_N,
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    previous_1grams: tuple[tuple[str, ...], ...] | None = None,
    leftovers: tuple[tuple[tuple[str, ...], int, int, tuple], ...] | None = None,
) -> bool:
    """True iff all leftover remaining-after-076-010 previous 1-grams are I-only.

    Claim holds only if leftover matching sites still compute as
    those 11, every leftover matching site has a previous token so
    the 1-gram set is complete relative to N=11, the five leftover
    4-grams still compute, and every previous 1-gram has N_I>=1
    and N_off_I=0. Extra I does not make the claim lose. Nested
    leftover 4-gram / leftover 2-gram LOSE / leftover 1-gram LOSE /
    previous 2-gram LOSE / extra-I leftover-1-gram 2-grams HOLD /
    unique previous stem do not make this claim lose.
    """
    if leftovers is None:
        leftovers = leftover_n4_rows()
    remaining_grams = leftover_remaining_grams(leftovers)
    if leftover_sites is None:
        leftover_sites = leftover_matching_4gram_sites()
    if previous_1grams is None:
        previous_1grams = leftover_remaining_prev1()
    stems = leftover_4gram_previous_stems(load_i_sides())
    return (
        remaining_grams == CYCLE340_SEQUENCES
        and leftover_sites == STANDING_LEFTOVER_MATCHING_4GRAM_SITES
        and len(leftover_sites) == expected_n
        and None not in stems
        and len(stems) == expected_n
        and previous_1grams == sequences
        and len(n_i) == expected_n
        and len(n_off_i) == expected_n
        and all(
            sequence_is_i_only(on, off)
            for on, off in zip(n_i, n_off_i, strict=True)
        )
    )


