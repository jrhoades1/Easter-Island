def rank_remaining_after_999_next087_next_stems(
    counts: Counter,
) -> tuple[tuple[str, int], ...]:
    """Next-of-087 stems by count, then larger Barthel id."""
    return tuple(
        sorted(
            counts.items(),
            key=lambda item: (-item[1], -barthel_id(item[0])),
        )
    )


def select_remaining_after_999_next087_g(
    remaining_stems: tuple[str, ...],
) -> tuple[str | None, int, bool]:
    """Return (G, K, uniquely_most_frequent). Empty with-next has no G."""
    ranked = rank_remaining_after_999_next087_next_stems(
        remaining_after_999_next087_next_stem_counts(remaining_stems)
    )
    if not ranked:
        return (None, 0, False)
    gram, count = ranked[0]
    unique = sum(1 for _stem, other in ranked if other == count) == 1
    return (gram, count, unique)


def remaining_after_999_next087_next_stem_frequency_table(
    sites: tuple[tuple[str, str, int], ...],
    next_stems: tuple[str | None, ...],
    next_4grams: tuple[tuple[str, ...] | None, ...],
) -> tuple[
    tuple[str, int, tuple[tuple[str, str, int], ...], tuple[tuple[str, ...], ...]],
    ...,
]:
    """Next-of-087 frequency: highest count first, then larger id."""
    with_next = leftover_n4_remaining_remaining_after_999_next087_with_next(
        sites, next_stems
    )
    stems = tuple(nxt for nxt in next_stems if nxt is not None)
    grams = tuple(gram for gram in next_4grams if gram is not None)
    first_seen = group_sites_by_next_stem(with_next, stems)
    grams_by_stem: dict[str, list[tuple[str, ...]]] = {
        stem: [] for stem, _ in first_seen
    }
    for nxt, gram in zip(stems, grams, strict=True):
        grams_by_stem[nxt].append(gram)
    rows = tuple(
        (stem, len(stem_sites), stem_sites, tuple(grams_by_stem[stem]))
        for stem, stem_sites in first_seen
    )
    return tuple(sorted(rows, key=lambda row: (-row[1], -barthel_id(row[0]))))


