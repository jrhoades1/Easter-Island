def i_leftover_n4_remaining_021_090_076_remaining_after_999_next087_unique_next_stem(
    sites: tuple[tuple[str, str, int], ...],
    next_stems: tuple[str | None, ...],
    previous_4grams: tuple[tuple[str, ...] | None, ...],
    next_4grams: tuple[tuple[str, ...] | None, ...],
    hapax_4grams: tuple[tuple[str, ...], ...] = LOCKED_HAPAX_PREVIOUS_4GRAMS,
    expected_n: int = STANDING_N,
    locked_next: str = LOCKED_NEXT_087,
) -> bool:
    """True iff N=3 hapax 600/007/150 next-087 sites have a unique most frequent next-of-087."""
    if sites != STANDING_SITES:
        return False
    if len(sites) != expected_n:
        return False
    hapax_set = set(hapax_4grams)
    if any(prev4 not in hapax_set for prev4 in previous_4grams):
        return False
    if any(
        gram is None or gram[:3] != (GRAM2[0], GRAM2[1], locked_next)
        for gram in next_4grams
    ):
        return False
    with_next = leftover_n4_remaining_remaining_after_999_next087_with_next(
        sites, next_stems
    )
    stems = tuple(nxt for nxt in next_stems if nxt is not None)
    if len(with_next) != len(stems):
        return False
    gram, count, unique = select_remaining_after_999_next087_g(stems)
    return bool(unique and gram is not None and count >= 2)


