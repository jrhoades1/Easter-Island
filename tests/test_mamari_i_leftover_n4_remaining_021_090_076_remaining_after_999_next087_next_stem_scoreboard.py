def site_next_of_087_stem(
    stems: list[str],
    index: int,
    gram2: tuple[str, ...] = GRAM2,
    locked_next: str = LOCKED_NEXT_087,
) -> str | None:
    """Token immediately after 087 in 090 076 087 X; None if missing."""
    nxt4 = site_next_4gram(stems, index, gram2)
    if nxt4 is None:
        return None
    if nxt4[:3] != (gram2[0], gram2[1], locked_next):
        return None
    return nxt4[3]


