def i_leftover_n4_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_extra_i_prev1_2grams_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    extra_sites: tuple[tuple[str, str, int], ...],
    rows: tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...],
    grams: tuple[tuple[str, ...], ...],
    n_extra_total: int,
    leftover_prev1_still: bool,
    expected_extra_sites: tuple[tuple[str, str, int], ...] = STANDING_EXTRA_I_SITES_FLAT,
    expected_n_extra: int = STANDING_N_EXTRA_I,
    expected_n: int = STANDING_N_DISTINCT_2GRAMS,
) -> bool:
    """True iff extra I=4, complete next 2-grams, all I-only.

    Hapax is not required. Loses if any extra-I 2-gram appears
    off I, if extra_I_total != 4, if an extra-I site is
    line-final so the 2-gram set is empty relative to
    extra_I_total=4, if extra I of I-only previous 1-grams
    with extra I no longer computes, or if previous 1-grams
    no longer compute. Leftover matching previous-2-grams of
    leftover 4-grams stay nested and do not make the claim
    lose. Extra I of leftover matching previous-2-grams is
    not this cycle's claim.
    """
    if not leftover_prev1_still:
        return False
    if n_extra_total != expected_n_extra:
        return False
    if extra_sites != expected_extra_sites:
        return False
    if any(gram is None for gram, _site, _role, _parent in rows):
        return False
    if len(grams) != expected_n or len(n_i) != expected_n or len(n_off_i) != expected_n:
        return False
    if any(gram in CYCLE340_SEQUENCES for gram in grams):
        return False
    if not all(
        sequence_is_i_only(on, off)
        for on, off in zip(n_i, n_off_i, strict=True)
    ):
        return False
    return len(rows) == expected_n_extra


