def leaking_prev2_with_extra_i(
    sequences: tuple[tuple[str, ...], ...] = CYCLE406_SEQUENCES,
    extra_each: tuple[tuple[tuple[str, str, int], ...], ...] | None = None,
    leaking: tuple[tuple[str, ...], ...] = CYCLE406_LEAKING,
) -> tuple[tuple[str, ...], ...]:
    """Leaking leftover remaining-after-076-010 previous 2-grams whose extra I is nonempty."""
    if extra_each is None:
        extra_each = tuple(
            extra_i_sites_of_2gram(nge4_sites(gram, load_i_sides()), matching)
            for gram, matching in zip(
                sequences, leftover_matching_prev2_sites_each(), strict=True
            )
        )
    leak_set = set(leaking)
    return tuple(
        gram
        for gram, extra in zip(sequences, extra_each, strict=True)
        if extra and gram in leak_set
    )


