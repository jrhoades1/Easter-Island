def i_leftover_n4_remaining_090_076_remaining_after_600_unique_previous_stem(
    inside_sites: tuple[tuple[str, str, int], ...],
    previous_stems: tuple[str | None, ...],
    locked: tuple[str, ...] = LOCKED_PREVIOUS_STEMS_AFTER_600,
) -> bool:
    """True iff remaining-after-600 has a unique most frequent previous stem with K ≥ 2."""
    remaining = leftover_n4_remaining_remaining_after_600(
        inside_sites,
        previous_stems,
        locked,
    )
    remaining_stems = leftover_n4_remaining_remaining_after_600_previous_stems(
        inside_sites,
        previous_stems,
        locked,
    )
    if len(remaining) != STANDING_N_REMAINING_AFTER_600:
        return False
    if remaining != leftover_n4_remaining_remaining_after_021_without_previous_600(
        inside_sites,
        previous_stems,
    ):
        return False
    gram, count, unique = select_remaining_after_600_g(remaining_stems)
    return bool(unique and gram is not None and count >= 2)


