def site_prev_5gram_for_4gram(
    stems: list[str],
    index: int,
    gram4: tuple[str, ...],
) -> tuple[str, ...] | None:
    """V X Y Z W if the previous token exists; None at line-initial or mismatch."""
    if tuple(stems[index : index + len(gram4)]) != gram4:
        return None
    if index < 1:
        return None
    return tuple(stems[index - 1 : index + len(gram4)])


def prev4_5gram_site(
    extra_site: tuple[str, str, int],
) -> tuple[str, str, int] | None:
    """5-gram starts one token before the extra-I previous-4 start."""
    side, line, index = extra_site
    if index < 1:
        return None
    return (side, line, index - 1)


