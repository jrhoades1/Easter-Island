    """Previous token plus previous 3-gram at extra I sites; leftover matching starts excluded.

    Leftover matching previous-4 / leftover matching leftover-n4 extra-I
    previous-3-gram 4-grams are recorded, not skipped.
    """
    if leftover_matching_prev3_starts is None:
        leftover_matching_prev3_starts = leftover_matching_prev3_sites()
    if leftover_matching_leftover2_starts is None:
        leftover_matching_leftover2_starts = leftover_matching_leftover2_of_leftover5()
