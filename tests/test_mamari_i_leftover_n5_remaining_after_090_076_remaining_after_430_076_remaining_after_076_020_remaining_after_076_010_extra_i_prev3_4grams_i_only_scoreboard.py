def i_leftover_n5_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_extra_i_prev3_4grams_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    extra_sites: tuple[tuple[str, str, int], ...],
    rows: tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...],
    grams: tuple[tuple[str, ...], ...],
    n_extra_total: int,
    leftover_prev3_still: bool,
    n_line_initial: int = 0,
    n_no_prev4: int = 0,
    expected_extra_sites: tuple[tuple[str, str, int], ...] = STANDING_EXTRA_I_SITES_FLAT,
    expected_n_extra: int = STANDING_N_EXTRA_I,
    expected_n: int = STANDING_N_DISTINCT_4GRAMS,
    expected_n_rows: int = STANDING_N_EXTRA_I_4GRAMS,
) -> bool:
    """True iff extra I=4, complete previous 4-grams, all I-only.

    Hapax is not required. Loses if any extra-I 4-gram appears
    off I, if extra_I_total != 4, if an extra-I site is
    line-initial so the 4-gram set is incomplete relative to
    extra_I_total=4, if extra I of I-only previous 3-grams with
    extra I no longer computes, or if leftover-5 previous 3-grams
    no longer compute. Leftover matching leftover-5 remaining /
    leftover matching previous-3 / leftover matching previous-4 of
    leftover 5-grams stay nested and do not make the claim lose.
    Extra I of leftover matching leftover-5 remaining / leftover
    matching previous-4 is not this cycle's claim. Incomplete-set
    is LOSE. Any N_leak>0 is LOSE. N_no_prev4 / N_line_initial
    means incomplete-set LOSE even if every existing 4-gram is
    I-only.
    """
    if not leftover_prev3_still:
        return False
    if n_extra_total != expected_n_extra:
        return False
    if extra_sites != expected_extra_sites:
        return False
    if n_line_initial or n_no_prev4:
        return False
    if len(rows) != expected_n_rows:
        return False
    if any(gram is None for gram, _site, _role, _parent in rows):
        return False
    if grams != tuple(dict.fromkeys(gram for gram, _site, _role, _parent in rows)):
        return False
    if len(grams) != expected_n:
        return False
    if len(n_i) != expected_n or len(n_off_i) != expected_n:
        return False
    if any(off > 0 for off in n_off_i):
        return False
    if any(on < 1 for on in n_i):
        return False
    return True


