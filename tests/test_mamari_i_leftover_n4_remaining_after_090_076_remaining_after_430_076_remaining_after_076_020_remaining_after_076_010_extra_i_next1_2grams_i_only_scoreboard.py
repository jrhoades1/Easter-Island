def extra_i_next1_2grams_at_sites(
    i_sides: dict[str, list[list[str]]],
    extra_sites: tuple[tuple[str, str, int], ...],
    parent_1grams: tuple[tuple[str, ...], ...],
    leftover_matching_next1_starts: tuple[tuple[str, str, int], ...] | None = None,
    leftover_matching_leftover2_starts: tuple[tuple[str, str, int], ...] | None = None,
) -> tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...]:
    """Next 1-gram plus next token at extra I sites; leftover matching starts excluded."""
    if leftover_matching_next1_starts is None:
        leftover_matching_next1_starts = leftover_matching_next1_sites()
    if leftover_matching_leftover2_starts is None:
        leftover_matching_leftover2_starts = tuple(
            site for row in leftover_matching_2gram_sites_each() for site in row
        )
    leftover_next1_starts = set(leftover_matching_next1_starts)
    leftover_2_starts = set(leftover_matching_leftover2_starts)
    leftover_4_set = set(CYCLE340_SEQUENCES)
    out: list[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]]] = []
    for site, gram1 in zip(extra_sites, parent_1grams, strict=True):
        if site in leftover_next1_starts:
            continue
        if site in leftover_2_starts:
            continue
        stems = line_stems_for_site(i_sides, site)
        next2 = site_next_2gram_for_1gram(stems, site[2], gram1)
        if next2 is None:
            continue
        if next2 in leftover_4_set:
            continue
        out.append((next2, site, "next", gram1))
    return tuple(out)


def distinct_extra_i_2grams(
    rows: tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...],
) -> tuple[tuple[str, ...], ...]:
    """First-seen distinct extra-I next-1-gram 2-grams."""
    seen_grams: list[tuple[str, ...]] = []
    for gram, _site, _role, _parent in rows:
        if gram not in seen_grams:
            seen_grams.append(gram)
    return tuple(seen_grams)


def leaking_2grams(
    sequences: tuple[tuple[str, ...], ...],
    n_off_i: tuple[int, ...],
) -> tuple[tuple[str, ...], ...]:
    """Distinct extra-I next-1-gram 2-grams with N_off_I>0."""
    return tuple(
        gram
        for gram, off in zip(sequences, n_off_i, strict=True)
        if off > 0
    )


def extra_i_next1_site_covered_by_2gram(
    extra_site: tuple[str, str, int],
    i_sites: tuple[tuple[str, str, int], ...],
) -> bool:
    """True iff the extra I next-1-gram site sits inside its extra-I 2-gram."""
    return extra_site in i_sites


def i_leftover_n4_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_extra_i_next1_2grams_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    extra_sites: tuple[tuple[str, str, int], ...],
    rows: tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...],
    grams: tuple[tuple[str, ...], ...],
    n_extra_total: int,
    leftover_next1_still: bool,
    expected_extra_sites: tuple[tuple[str, str, int], ...] = STANDING_EXTRA_I_SITES_FLAT,
    expected_n_extra: int = STANDING_N_EXTRA_I,
    expected_n: int = STANDING_N_DISTINCT_2GRAMS,
) -> bool:
    """True iff extra I=1, complete next 2-grams, all I-only.

    Hapax is not required. Loses if any extra-I 2-gram appears
    off I, if extra_I_total != 1, if an extra-I site is
    line-final so the 2-gram set is incomplete relative to
    extra_I_total=1, if extra I of I-only next 1-grams with
    extra I no longer computes, or if next 1-grams no longer
    compute. Leftover matching leftover-2 / next-2 of leftover
    4-grams stay nested and do not make the claim lose. Extra
    I of leftover matching leftover-2 / next-2 is not this
    cycle's claim. Incomplete-set is LOSE.
    """
    if not leftover_next1_still:
        return False
    if n_extra_total != expected_n_extra:
        return False
    if extra_sites != expected_extra_sites:
        return False
    if any(gram is None for gram, _site, _role, _parent in rows):
        return False
    if len(grams) != expected_n or len(n_i) != expected_n or len(n_off_i) != expected_n:
        return False
    if any(gram in CYCLE340_SEQUENCES for gram in grams):
        return False
    if not all(
        sequence_is_i_only(on, off)
        for on, off in zip(n_i, n_off_i, strict=True)
    ):
        return False
    return len(rows) == expected_n_extra


