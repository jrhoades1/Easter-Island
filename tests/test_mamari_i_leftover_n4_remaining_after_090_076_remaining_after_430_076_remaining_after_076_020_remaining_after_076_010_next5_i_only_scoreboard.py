def next_5gram_site(
    leftover_site: tuple[str, str, int],
) -> tuple[str, str, int]:
    """Next 5-gram starts immediately after leftover 4-gram."""
    side, line, index = leftover_site
    return (side, line, index + 4)


def leftover_4gram_site_for_next5(
    site: tuple[str, str, int],
) -> tuple[str, str, int]:
    """Leftover 4-gram starts four tokens before the next-5 start."""
    side, line, index = site
    return (side, line, index - 4)


def site_next_5gram_after_4gram(
    stems: list[str],
    index: int,
    gram4: tuple[str, ...],
) -> tuple[str, ...] | None:
    """Five tokens after leftover 4-gram; None if fewer than five follow."""
    first = site_next_stem_after_4gram(stems, index, gram4)
    if first is None:
        return None
    fifth_index = index + len(gram4) + 4
    if fifth_index >= len(stems):
        return None
    return tuple(stems[index + len(gram4) + k] for k in range(5))


def leftover_4gram_next_5grams(
    i_sides: dict[str, list[list[str]]] | None = None,
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    grams4: tuple[tuple[str, ...], ...] = STANDING_PARENT_4GRAMS,
) -> tuple[tuple[str, ...] | None, ...]:
    """Next 5-grams in leftover-matching-site order; None if incomplete."""
    if i_sides is None:
        i_sides = load_i_sides()
    if leftover_sites is None:
        leftover_sites = leftover_matching_4gram_sites()
    return tuple(
        site_next_5gram_after_4gram(line_stems_for_site(i_sides, site), site[2], gram)
        for site, gram in zip(leftover_sites, grams4, strict=True)
    )


def leftover_remaining_next5(
    i_sides: dict[str, list[list[str]]] | None = None,
) -> tuple[tuple[str, ...], ...]:
    """Next 5-grams that exist (drops None)."""
    return tuple(gram for gram in leftover_4gram_next_5grams(i_sides) if gram is not None)


def leftover_matching_next5_sites(
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    next_5grams: tuple[tuple[str, ...] | None, ...] | None = None,
) -> tuple[tuple[str, str, int], ...]:
    """Leftover matching next-5-gram starts (sites that have five following tokens)."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_4gram_sites()
    if next_5grams is None:
        next_5grams = leftover_4gram_next_5grams()
    return tuple(
        next_5gram_site(site)
        for site, gram in zip(leftover_sites, next_5grams, strict=True)
        if gram is not None
    )


def leftover_matching_next5_sites_each(
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    sequences: tuple[tuple[str, ...], ...] = STANDING_SEQUENCES,
) -> tuple[tuple[tuple[str, str, int], ...], ...]:
    """Per next 5-gram leftover matching next-5-gram sites."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_4gram_sites()
    next_5grams = leftover_4gram_next_5grams()
    next_sites = leftover_matching_next5_sites(leftover_sites, next_5grams)
    buckets: dict[tuple[str, ...], list[tuple[str, str, int]]] = {
        gram: [] for gram in sequences
    }
    for gram, site in zip(
        (g for g in next_5grams if g is not None),
        next_sites,
        strict=True,
    ):
        buckets[gram].append(site)
    return tuple(tuple(buckets[gram]) for gram in sequences)


