def extra_i_next1_2grams_at_sites(
    i_sides: dict[str, list[list[str]]],
    extra_sites: tuple[tuple[str, str, int], ...],
    parent_1grams: tuple[tuple[str, ...], ...],
    leftover_matching_next1_starts: tuple[tuple[str, str, int], ...] | None = None,
) -> tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...]:
    """Next 1-gram plus next token at extra I sites of I-only leftover-6 next 1-grams."""
    if leftover_matching_next1_starts is None:
        leftover_matching_next1_starts = leftover_matching_next1_sites()
    leftover_next1_starts = set(leftover_matching_next1_starts)
    out: list[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]]] = []
    for site, gram1 in zip(extra_sites, parent_1grams, strict=True):
        if site in leftover_next1_starts:
            continue
        stems = line_stems_for_site(i_sides, site)
        next2 = site_next_2gram_for_1gram(stems, site[2], gram1)
        if next2 is None:
            continue
        out.append((next2, site, "next", gram1))
    return tuple(out)


