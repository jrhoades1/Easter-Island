def previous_2gram_site(
    leftover_site: tuple[str, str, int],
) -> tuple[str, str, int] | None:
    """Previous 2-gram starts two tokens before leftover 5-gram."""
    side, line, index = leftover_site
    if index < STANDING_N2:
        return None
    return (side, line, index - STANDING_N2)


def leftover_5gram_site_for_prev2(
    site: tuple[str, str, int],
) -> tuple[str, str, int]:
    """Leftover 5-gram starts two tokens after the previous-2 start."""
    side, line, index = site
    return (side, line, index + STANDING_N2)


def leftover_5gram_previous_2grams(
    i_sides: dict | None = None,
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    leftover_5grams: tuple[tuple[str, ...], ...] | None = None,
) -> tuple[tuple[str, ...] | None, ...]:
    """Per leftover matching leftover-5 remaining site, the previous 2-gram or None."""
    if i_sides is None:
        i_sides = load_i_sides()
    if leftover_sites is None:
        leftover_sites = leftover_matching_5gram_sites()
    if leftover_5grams is None:
        leftover_5grams = leftover_remaining_5grams(i_sides=i_sides)
    out: list[tuple[str, ...] | None] = []
    for site, gram in zip(leftover_sites, leftover_5grams, strict=True):
        side, line, index = site
        stems = i_sides[side][IA_LINE_NAMES.index(line)]
        if tuple(stems[index : index + STANDING_N5]) != gram:
            out.append(None)
            continue
        if index >= STANDING_N2:
            out.append((stems[index - STANDING_N2], stems[index - 1]))
        else:
            out.append(None)
    return tuple(out)


def leftover_remaining_prev2(
    i_sides: dict | None = None,
) -> tuple[tuple[str, ...], ...]:
    """Previous 2-grams in leftover-matching leftover-5 remaining site order."""
    return tuple(gram for gram in leftover_5gram_previous_2grams(i_sides) if gram is not None)


def leftover_matching_prev2_sites(
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    previous_2grams: tuple[tuple[str, ...] | None, ...] | None = None,
) -> tuple[tuple[str, str, int], ...]:
    """Leftover matching previous-2-gram starts (two tokens before leftover 5-grams)."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_5gram_sites()
    if previous_2grams is None:
        previous_2grams = leftover_5gram_previous_2grams()
    return tuple(
        previous_2gram_site(site)
        for site, gram in zip(leftover_sites, previous_2grams, strict=True)
        if gram is not None
    )


def leftover_matching_prev2_sites_each(
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
) -> tuple[tuple[tuple[str, str, int], ...], ...]:
    """Per leftover-5 remaining site leftover matching previous-2-gram site."""
    return tuple((site,) for site in leftover_matching_prev2_sites(leftover_sites))


def leftover_matching_equals_prev2_plus_two(
    leftover_sites: tuple[tuple[str, str, int], ...] = STANDING_LEFTOVER_MATCHING_5GRAM_SITES,
    matching_prev2_sites: tuple[tuple[str, str, int], ...] = STANDING_LEFTOVER_MATCHING_PREV2_SITES,
) -> bool:
    """True iff leftover matching leftover-5 remaining sites equal previous-2 starts plus two."""
    measured = set(leftover_5gram_site_for_prev2(site) for site in matching_prev2_sites)
    return set(leftover_sites) == measured


