def leftover_matching_next3_sites(
    leftover_sites=None,
    i_sides=None,
):
    """Leftover matching next-3 starts: leftover matching next-1 sites with next-two."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_4gram_sites()
    if i_sides is None:
        i_sides = load_i_sides()
    out = []
    for site in leftover_matching_next1_sites(leftover_sites):
        stems = line_stems_for_site(i_sides, site)
        parent = (stems[site[2]],) if site[2] < len(stems) else ()
        if site_next_3gram_for_1gram(stems, site[2], parent) is not None:
            out.append(site)
    return tuple(out)


def leftover_matching_next3_grams(
    leftover_sites=None,
    i_sides=None,
):
    """3-grams starting at leftover matching next-1 sites (nested, not this cycle)."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_4gram_sites()
    if i_sides is None:
        i_sides = load_i_sides()
    out = []
    for site in leftover_matching_next1_sites(leftover_sites):
        stems = line_stems_for_site(i_sides, site)
        parent = (stems[site[2]],) if site[2] < len(stems) else ()
        gram3 = site_next_3gram_for_1gram(stems, site[2], parent)
        if gram3 is not None:
            out.append(gram3)
    return tuple(out)


def extra_i_next1_3grams_at_sites(
    i_sides,
    extra_sites,
    parent_1grams,
    leftover_matching_next1_starts=None,
    leftover_matching_leftover2_starts=None,
    leftover_matching_leftover3_starts=None,
):
    """Next 1-gram plus next two at extra I sites; leftover matching starts excluded."""
    if leftover_matching_next1_starts is None:
        leftover_matching_next1_starts = leftover_matching_next1_sites()
    if leftover_matching_leftover2_starts is None:
        leftover_matching_leftover2_starts = tuple(
            site for row in leftover_matching_2gram_sites_each() for site in row
        )
    if leftover_matching_leftover3_starts is None:
        leftover_matching_leftover3_starts = tuple(
            site for row in leftover_matching_3gram_sites_each() for site in row
        )
    leftover_next1_starts = set(leftover_matching_next1_starts)
    leftover_2_starts = set(leftover_matching_leftover2_starts)
    leftover_3_starts = set(leftover_matching_leftover3_starts)
    leftover_4_set = set(CYCLE340_SEQUENCES)
    out = []
    for site, gram1 in zip(extra_sites, parent_1grams, strict=True):
        if site in leftover_next1_starts:
            continue
        if site in leftover_2_starts:
            continue
        if site in leftover_3_starts:
            continue
        stems = line_stems_for_site(i_sides, site)
        next3 = site_next_3gram_for_1gram(stems, site[2], gram1)
        if next3 is None:
            continue
        if next3 in leftover_4_set:
            continue
        out.append((next3, site, "next", gram1))
    return tuple(out)


