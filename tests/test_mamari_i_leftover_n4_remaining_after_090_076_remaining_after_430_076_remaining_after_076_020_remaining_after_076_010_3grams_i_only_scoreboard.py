def leftover_remaining_3grams(
    leftovers: tuple[tuple[tuple[str, ...], int, int, tuple], ...] | None = None,
) -> tuple[tuple[str, ...], ...]:
    """Contiguous 3-grams of the five remaining-after-076-010 leftover 4-grams."""
    grams4 = leftover_remaining_grams(leftovers)
    out: list[tuple[str, ...]] = []
    for gram4 in grams4:
        out.append(gram4[:3])
        out.append(gram4[1:])
    return tuple(out)


def leftover_matching_3gram_sites_each(
    remaining: tuple[tuple[tuple[str, ...], int, int, tuple], ...] | None = None,
) -> tuple[tuple[tuple[str, str, int], ...], ...]:
    """Leftover-derived 3-gram starts: prefix at leftover 4-gram site, suffix at +1."""
    if remaining is None:
        remaining = leftover_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010()
    out: list[tuple[tuple[str, str, int], ...]] = []
    for _gram4, _n, _f, sites in remaining:
        prefix_sites = tuple(sites)
        suffix_sites = tuple((side, line, index + 1) for side, line, index in sites)
        out.append(prefix_sites)
        out.append(suffix_sites)
    return tuple(out)


def extra_i_sites_of_3gram(
    i_sites: tuple[tuple[str, str, int], ...],
    leftover_matching: tuple[tuple[str, str, int], ...],
) -> tuple[tuple[str, str, int], ...]:
    """I 3-gram sites outside leftover-derived 3-gram starts of the five leftovers."""
    leftover_set = set(leftover_matching)
    return tuple(site for site in i_sites if site not in leftover_set)


def sequence_is_i_only(n_i: int, n_off_i: int) -> bool:
    """True iff N_I>=1 and N_off_I=0."""
    return n_i >= 1 and n_off_i == 0


def leaking_3grams(
    sequences: tuple[tuple[str, ...], ...],
    n_off_i: tuple[int, ...],
) -> tuple[tuple[str, ...], ...]:
    """Distinct leftover 3-grams with N_off_I>0."""
    return tuple(
        gram
        for gram, off in zip(sequences, n_off_i, strict=True)
        if off > 0
    )


def i_leftover_n4_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_3grams_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    sequences: tuple[tuple[str, ...], ...] = STANDING_SEQUENCES,
    expected_n: int = STANDING_N,
    leftovers: tuple[tuple[tuple[str, ...], int, int, tuple], ...] | None = None,
) -> bool:
    """True iff all ten leftover remaining-after-076-010 3-grams are I-only.

    Claim holds only if the leftover inventory still yields exactly those
    ten contiguous 3-grams and every one of them has N_I>=1 and
    N_off_I=0. Extra I does not make the claim lose. Nested cycle 340
    leftover 4-gram I-only does not make this claim lose.
    """
    if leftovers is None:
        leftovers = leftover_n4_rows()
    remaining_grams = leftover_remaining_3grams(leftovers)
    return (
        remaining_grams == sequences
        and len(n_i) == expected_n
        and len(n_off_i) == expected_n
        and all(
            sequence_is_i_only(on, off)
            for on, off in zip(n_i, n_off_i, strict=True)
        )
    )


