def site_next_4gram_for_3gram(
    stems: list[str],
    index: int,
    gram3: tuple[str, ...],
) -> tuple[str, ...] | None:
    """Leftover-6 next 3-gram plus the next token, or None if line-final."""
    if tuple(stems[index : index + 3]) != gram3:
        return None
    if index + 3 >= len(stems):
        return None
    return (stems[index], stems[index + 1], stems[index + 2], stems[index + 3])


