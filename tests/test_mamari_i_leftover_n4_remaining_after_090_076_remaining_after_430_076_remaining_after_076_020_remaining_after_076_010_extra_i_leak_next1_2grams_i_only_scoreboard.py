def i_leftover_n4_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_extra_i_leak_next1_2grams_all_i_only(
    n_i,
    n_off_i,
    extra_sites,
    rows,
    grams,
    n_extra_total,
    leftover_next1_still,
    expected_extra_sites=None,
    expected_n_extra=None,
    expected_n=None,
):
    """True iff extra I=771, complete next 2-grams, all I-only.

    Hapax is not required. Loses if any extra-I 2-gram appears
    off I, if extra_I_total != 771, if an extra-I site is
    line-final so the 2-gram set is incomplete relative to
    extra_I_total=771, if leftover matching leftover-2 starts
    are excluded so the set is incomplete, if extra I of
    leaking next 1-grams no longer computes, or if next
    1-grams no longer compute. Leftover matching leftover-2 /
    next-2 of leftover 4-grams stay nested and do not make
    the claim lose by themselves. Extra I of leftover matching
    leftover-2 / next-2 is not this cycle's claim. Incomplete-
    set is LOSE. Any N_leak>0 is LOSE.
    """
    if expected_extra_sites is None:
        expected_extra_sites = STANDING_EXTRA_I_SITES_FLAT
    if expected_n_extra is None:
        expected_n_extra = STANDING_N_EXTRA_I
    if expected_n is None:
        expected_n = STANDING_N_DISTINCT_2GRAMS
    if not leftover_next1_still:
        return False
    if n_extra_total != expected_n_extra:
        return False
    if extra_sites != expected_extra_sites:
        return False
    if any(gram is None for gram, _site, _role, _parent in rows):
        return False
    if len(grams) != expected_n or len(n_i) != expected_n or len(n_off_i) != expected_n:
        return False
    if any(gram in CYCLE340_SEQUENCES for gram in grams):
        return False
    if not all(
        sequence_is_i_only(on, off)
        for on, off in zip(n_i, n_off_i, strict=True)
    ):
        return False
    return len(rows) == expected_n_extra


