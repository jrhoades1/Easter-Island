def flatten_extra_i_sites(
    extra_each: tuple[tuple[tuple[str, str, int], ...], ...] = CYCLE341_EXTRA_I_SITES,
) -> tuple[tuple[str, str, int], ...]:
    """Flatten per-3-gram extra I rows into leftover-of-leftover extra I sites."""
    return tuple(site for row in extra_each for site in row)


def site_previous_4gram_for_3gram(
    stems: list[str],
    index: int,
    gram3: tuple[str, ...],
) -> tuple[str, ...] | None:
    """W X Y Z if a previous stem exists; None at start-of-line or mismatch."""
    if tuple(stems[index : index + len(gram3)]) != gram3:
        return None
    if index < 1:
        return None
    return tuple(stems[index - 1 : index + len(gram3)])


def site_next_4gram_for_3gram(
    stems: list[str],
    index: int,
    gram3: tuple[str, ...],
) -> tuple[str, ...] | None:
    """X Y Z W if a next stem exists; None at line-final or mismatch."""
    if tuple(stems[index : index + len(gram3)]) != gram3:
        return None
    if index + len(gram3) >= len(stems):
        return None
    return tuple(stems[index : index + len(gram3) + 1])


def extra_i_4grams_containing_3gram_at_sites(
    i_sides: dict[str, list[list[str]]],
    extra_sites: tuple[tuple[str, str, int], ...],
    parent_3grams: tuple[tuple[str, ...], ...],
    leftover_4grams: tuple[tuple[str, ...], ...] = CYCLE340_SEQUENCES,
    leftover_matching_4: tuple[tuple[str, str, int], ...] | None = None,
) -> tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...]:
    """Previous then next 4-grams at extra I sites; leftover 4-grams excluded."""
    if leftover_matching_4 is None:
        leftover_matching_4 = leftover_matching_4gram_sites()
    leftover_4_set = set(leftover_4grams)
    leftover_site_set = set(leftover_matching_4)
    out: list[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]]] = []
    for site, gram3 in zip(extra_sites, parent_3grams, strict=True):
        stems = line_stems_for_site(i_sides, site)
        prev4 = site_previous_4gram_for_3gram(stems, site[2], gram3)
        next4 = site_next_4gram_for_3gram(stems, site[2], gram3)
        if prev4 is not None and prev4 not in leftover_4_set:
            prev_start = (site[0], site[1], site[2] - 1)
            if prev_start not in leftover_site_set:
                out.append((prev4, site, "prev", gram3))
        if next4 is not None and next4 not in leftover_4_set:
            if site not in leftover_site_set:
                out.append((next4, site, "next", gram3))
    return tuple(out)


def distinct_extra_i_4grams(
    rows: tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...],
) -> tuple[tuple[str, ...], ...]:
    """First-seen distinct extra-I 4-grams."""
    seen: list[tuple[str, ...]] = []
    for gram, _site, _role, _parent in rows:
        if gram not in seen:
            seen.append(gram)
    return tuple(seen)


def leaking_4grams(
    sequences: tuple[tuple[str, ...], ...],
    n_off_i: tuple[int, ...],
) -> tuple[tuple[str, ...], ...]:
    """Distinct extra-I 4-grams with N_off_I>0."""
    return tuple(
        gram
        for gram, off in zip(sequences, n_off_i, strict=True)
        if off > 0
    )


def extra_i_3gram_site_covered_by_4gram(
    extra_site: tuple[str, str, int],
    role: str,
    i_sites: tuple[tuple[str, str, int], ...],
) -> bool:
    """True iff the extra I 3-gram site sits inside its extra-I 4-gram."""
    side, line, index = extra_site
    if role == "next":
        return extra_site in i_sites
    if role == "prev":
        return (side, line, index - 1) in i_sites
    return False


def i_leftover_n4_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_extra_i_4grams_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    extra_sites: tuple[tuple[str, str, int], ...],
    rows: tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...],
    grams: tuple[tuple[str, ...], ...],
    n_extra_total: int,
    leftover_3grams_still: bool,
    expected_extra_sites: tuple[tuple[str, str, int], ...] = STANDING_EXTRA_I_SITES_FLAT,
    expected_n_extra: int = STANDING_N_EXTRA_I,
    expected_n: int = STANDING_N_DISTINCT_4GRAMS,
    leftover_4grams: tuple[tuple[str, ...], ...] = CYCLE340_SEQUENCES,
) -> bool:
    """True iff extra I=5 at locked sites, complete 4-grams, all I-only.

    Hapax is not required. Loses if any extra-I 4-gram appears
    off I, if extra_I_total != 5, if an extra-I site is
    line-initial or line-final so the 4-gram set is empty
    relative to extra_I_total=5, if extra I of leftover
    3-grams no longer computes as those five sites, or if
    leftover 3-grams no longer compute. Leftover 4-grams of
    the five leftovers are excluded and do not make the
    claim lose.
    """
    if not leftover_3grams_still:
        return False
    if n_extra_total != expected_n_extra:
        return False
    if extra_sites != expected_extra_sites:
        return False
    if any(gram is None for gram, _site, _role, _parent in rows):
        return False
    if len(grams) != expected_n or len(n_i) != expected_n or len(n_off_i) != expected_n:
        return False
    if any(gram in leftover_4grams for gram in grams):
        return False
    if not all(
        sequence_is_i_only(on, off)
        for on, off in zip(n_i, n_off_i, strict=True)
    ):
        return False
    return len(rows) == expected_n


