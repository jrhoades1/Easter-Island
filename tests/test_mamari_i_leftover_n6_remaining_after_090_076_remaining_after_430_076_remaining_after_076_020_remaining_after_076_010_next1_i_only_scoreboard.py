def i_leftover_n6_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_next_1grams_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    sequences: tuple[tuple[str, ...], ...] = STANDING_SEQUENCES,
    expected_n: int = STANDING_N,
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    next_1grams: tuple[tuple[str, ...], ...] | None = None,
    leftovers: tuple[tuple[tuple[str, ...], int, int, tuple], ...] | None = None,
    i_sides: dict | None = None,
) -> bool:
    """True iff all leftover remaining-after-076-010 leftover 6-gram next 1-grams are I-only.

    Claim holds only if leftover matching leftover-6 remaining sites
    still compute as those 18, every leftover matching leftover-6
    remaining site has a next token so the 1-gram set is complete
    relative to N=18, the eighteen leftover 6-grams still compute,
    and every next 1-gram has N_I>=1 and N_off_I=0. Extra I does
    not make the claim lose. Nested leftover 6-gram / leftover
    5-gram / leftover 2-gram LOSE do not make this claim lose.
    """
    if leftovers is None:
        leftovers = leftover_n4_rows()
    remaining_6grams = leftover_remaining_6grams_distinct(leftovers, i_sides)
    if leftover_sites is None:
        leftover_sites = leftover_matching_6gram_sites(leftovers)
    if next_1grams is None:
        next_1grams = leftover_remaining_next1(i_sides)
    stems = leftover_6gram_next_stems(i_sides, leftover_sites, remaining_6grams)
    return (
        remaining_6grams == CYCLE457_SEQUENCES
        and leftover_sites == STANDING_LEFTOVER_MATCHING_6GRAM_SITES
        and len(leftover_sites) == expected_n
        and None not in stems
        and len(stems) == expected_n
        and next_1grams == sequences
        and len(n_i) == expected_n
        and len(n_off_i) == expected_n
        and all(
            sequence_is_i_only(on, off)
            for on, off in zip(n_i, n_off_i, strict=True)
        )
    )


