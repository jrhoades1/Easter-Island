def i_leftover_n5_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_next_5grams_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    sequences: tuple[tuple[str, ...], ...] = STANDING_SEQUENCES,
    expected_n: int = STANDING_N,
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    next_3grams: tuple[tuple[str, ...] | None, ...] | None = None,
    leftovers: tuple[tuple[tuple[str, ...], int, int, tuple], ...] | None = None,
    i_sides: dict | None = None,
) -> bool:
    """True iff all leftover remaining-after-076-010 leftover 5-gram next 4-grams are I-only.

    Claim holds only if leftover matching leftover-5 remaining sites
    still compute as those 12, every leftover matching leftover-5
    remaining site has four following tokens so the 4-gram set is
    complete relative to N=12, the twelve leftover 5-grams still
    compute, and every next 4-gram has N_I>=1 and N_off_I=0. Extra
    I does not make the claim lose. Incomplete set is LOSE. Nested
    leftover 5-gram / leftover 5-gram next 1-gram LOSE / leftover
    5-gram next 2-gram LOSE / leftover 2-gram LOSE / leftover n=4
    next 4-gram HOLD / extra-I next2 peels do not make this claim
    lose.
    """
    if leftovers is None:
        leftovers = leftover_n4_rows()
    remaining_5grams = leftover_remaining_5grams(leftovers, i_sides)
    if leftover_sites is None:
        leftover_sites = leftover_matching_5gram_sites(leftovers)
    if next_3grams is None:
        next_3grams = leftover_5gram_next_5grams(i_sides, leftover_sites, remaining_5grams)
    existing = tuple(gram for gram in next_3grams if gram is not None)
    return (
        remaining_5grams == CYCLE414_SEQUENCES
        and leftover_sites == STANDING_LEFTOVER_MATCHING_5GRAM_SITES
        and len(leftover_sites) == expected_n
        and None not in next_3grams
        and len(next_3grams) == expected_n
        and existing == sequences
        and len(n_i) == expected_n
        and len(n_off_i) == expected_n
        and all(
            sequence_is_i_only(on, off)
            for on, off in zip(n_i, n_off_i, strict=True)
        )
    )


