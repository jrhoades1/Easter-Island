def i_leftover_n4_remaining_090_076_remaining_after_600_remaining_after_020_3gram_090_076_057_i_only(
    i_hits: int,
    off_i_hits: int,
    n_remaining_next_057: int,
    leftover_sites: tuple[tuple[str, str, int], ...],
    still_computes: bool,
    expected_n: int = STANDING_N_REMAINING_AFTER_600_REMAINING_AFTER_020_NEXT_057,
    expected_sites: tuple[tuple[str, str, int], ...] = STANDING_LEFTOVER_MATCHING_SITES,
) -> bool:
    """True iff I ≥ 1, off-I is 0, N_next_057=2, leftover sites still compute.

    Extra I does not make the claim lose. Empty remainder after peeling
    057 does not make the claim lose.
    """
    return (
        i_hits >= 1
        and off_i_hits == 0
        and n_remaining_next_057 == expected_n
        and leftover_sites == expected_sites
        and still_computes
    )


def leftover_n4_remaining_remaining_after_600_remaining_after_020_next_057_subset(
    leftover_matching: tuple[tuple[str, str, int], ...] = STANDING_LEFTOVER_MATCHING_SITES,
    i_sites: tuple[tuple[str, str, int], ...] = STANDING_I_SITES,
) -> bool:
    """True iff leftover remaining-after-600 remaining-after-020 next-057 ⊆ I 090 076 057."""
    return set(leftover_matching).issubset(set(i_sites))


def extra_i_sites(
    i_sites: tuple[tuple[str, str, int], ...] = STANDING_I_SITES,
    leftover_matching: tuple[tuple[str, str, int], ...] = STANDING_LEFTOVER_MATCHING_SITES,
) -> tuple[tuple[str, str, int], ...]:
    """I 090 076 057 sites that are not leftover remaining-after-600 remaining-after-020 next-057."""
    leftover_set = set(leftover_matching)
    return tuple(site for site in i_sites if site not in leftover_set)


def named_off_i_sites(
    gram: tuple[str, ...] = GRAM3,
) -> tuple[tuple[str, str, int], ...]:
    """Named (side, line, index) hits on G, S, and T. Search only."""
    gk = load_g_k_sides()
    g_sites = nge8_sites(gram, gk)
    s_sites = nge6_sites(gram, load_s_sides())
    t = load_t_sides()
    t_sites = tuple(
        site_tuple(hit)
        for hit in named_side_hits(t[SIDE_TA], TA_LINE_NAMES, SIDE_TA, gram)
    )
    return g_sites + s_sites + t_sites


