def i_leftover_n5_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_extra_i_prev4_5grams_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    extra_sites: tuple[tuple[str, str, int], ...],
    rows: tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...],
    grams: tuple[tuple[str, ...], ...],
    n_extra_total: int,
    leftover_prev4_still: bool,
    n_line_initial: int = 0,
    expected_extra_sites: tuple[tuple[str, str, int], ...] = STANDING_EXTRA_I_SITES_FLAT,
    expected_n_extra: int = STANDING_N_EXTRA_I,
    expected_n: int = STANDING_N_DISTINCT_5GRAMS,
    expected_n_rows: int = STANDING_N_EXTRA_I_5GRAMS,
) -> bool:
    """True iff extra I=2, complete previous 5-grams, all I-only.

    Hapax is not required. Loses if any extra-I 5-gram appears
    off I, if extra_I_total != 2, if an extra-I site is
    line-initial so the 5-gram set is incomplete relative to
    extra_I_total=2, if extra I of I-only previous 4-grams with
    extra I no longer computes, or if leftover-5 previous 4-grams
    no longer compute. Leftover matching leftover-5 remaining /
    leftover matching previous-4 of leftover 5-grams stay nested
    and do not make the claim lose. Extra I of leftover matching
    leftover-5 remaining / leftover matching previous-4 is not
    this cycle's claim. Incomplete-set is LOSE. Any N_leak>0 is
    LOSE. N_no_prev / N_line_initial means incomplete-set LOSE
    even if every existing 5-gram is I-only.
    """
    if not leftover_prev4_still:
        return False
    if n_extra_total != expected_n_extra:
        return False
    if extra_sites != expected_extra_sites:
        return False
    if n_line_initial != 0:
        return False
    if any(gram is None for gram, _site, _role, _parent in rows):
        return False
    if len(grams) != expected_n or len(n_i) != expected_n or len(n_off_i) != expected_n:
        return False
    if any(gram in CYCLE340_SEQUENCES for gram in grams):
        return False
    if any(gram in CYCLE414_SEQUENCES for gram in grams):
        return False
    if any(gram in leftover_n4_matching_prev5_grams() for gram in grams):
        return False
    if not all(
        sequence_is_i_only(on, off)
        for on, off in zip(n_i, n_off_i, strict=True)
    ):
        return False
    return len(rows) == expected_n_rows


