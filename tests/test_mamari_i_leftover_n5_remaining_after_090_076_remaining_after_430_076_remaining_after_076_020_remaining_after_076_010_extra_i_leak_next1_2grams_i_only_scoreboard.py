def leftover_matching_next2_sites_of_leftover5(
    leftover_sites=None,
    i_sides=None,
):
    """Leftover matching next-2 starts after leftover 5-gram next-1 sites."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_5gram_sites()
    if i_sides is None:
        i_sides = load_i_sides()
    out = []
    for site in leftover_matching_next1_sites(leftover_sites):
        stems = line_stems_for_site(i_sides, site)
        parent = (stems[site[2]],) if site[2] < len(stems) else ()
