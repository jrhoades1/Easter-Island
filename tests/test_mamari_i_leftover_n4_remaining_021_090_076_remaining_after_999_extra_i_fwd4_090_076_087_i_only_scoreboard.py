def i_leftover_n4_remaining_021_090_076_remaining_after_999_extra_i_fwd4_090_076_087_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    extra_sites: tuple[tuple[str, str, int], ...],
    per_site_4grams: tuple[tuple[str, ...] | None, ...],
    i_sites_each: tuple[tuple[tuple[str, str, int], ...], ...],
    grams: tuple[tuple[str, ...], ...],
    n_extra_total: int,
    still_computes: bool,
    expected_extra_sites: tuple[tuple[str, str, int], ...] = STANDING_EXTRA_I_SITES,
    expected_n_extra: int = STANDING_N_EXTRA_I,
    expected_n: int = STANDING_N_DISTINCT_4GRAMS,
) -> bool:
    """True iff extra_I_total=2 at Ia3[87]/Ia4[162], complete 4-grams, all I-only.

    Hapax is not required. Loses if any extra-I 4-gram appears
    off I, if extra_I_total != 2, if an extra-I site is
    line-final so the 4-gram set is empty relative to
    extra_I_total=2, if extra I of 090 076 087 no longer
    computes as Ia3[87]/Ia4[162], or if nested remaining-
    after-999 next-087 no longer computes. Leftover-extra
    remaining-after-280 overlap does not make the claim lose.
    """
    if not still_computes:
        return False
    if n_extra_total != expected_n_extra:
        return False
    if extra_sites != expected_extra_sites:
        return False
    if any(gram is None for gram in per_site_4grams):
        return False
    if len(grams) != expected_n or len(n_i) != expected_n or len(n_off_i) != expected_n:
        return False
    if not all(
        sequence_is_i_only(on, off)
        for on, off in zip(n_i, n_off_i, strict=True)
    ):
        return False
    return extra_i_sites_covered_by_4grams(
        extra_sites,
        per_site_4grams,
        i_sites_each,
        grams,
    )


