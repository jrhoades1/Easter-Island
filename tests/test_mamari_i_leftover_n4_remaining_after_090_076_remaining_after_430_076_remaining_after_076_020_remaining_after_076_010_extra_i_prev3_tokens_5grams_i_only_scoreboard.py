def extra_i_prev3_tokens_5grams_at_sites(
    i_sides: dict[str, list[list[str]]],
    extra_sites: tuple[tuple[str, str, int], ...],
    parent_4grams: tuple[tuple[str, ...], ...],
    leftover_matching_leftover2_starts: tuple[tuple[str, str, int], ...] | None = None,
    leftover_matching_leftover3_starts: tuple[tuple[str, str, int], ...] | None = None,
    leftover_matching_leftover4_starts: tuple[tuple[str, str, int], ...] | None = None,
) -> tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...]:
    """Previous token plus extra-I previous-3-gram 4-gram at extra I sites.

    Leftover matching previous-4 / previous-5 are recorded, not
    skipped. Nested leftover-2 / leftover-3 / leftover-4 starts
    at the extra-I 4-gram site stay peeled (cycle 349 / 341 /
    340) and are not re-peeled as this construction.
    """
    if leftover_matching_leftover2_starts is None:
        leftover_matching_leftover2_starts = tuple(
            site for row in leftover_matching_2gram_sites_each() for site in row
        )
    if leftover_matching_leftover3_starts is None:
        leftover_matching_leftover3_starts = tuple(
            site for row in leftover_matching_3gram_sites_each() for site in row
        )
    if leftover_matching_leftover4_starts is None:
        leftover_matching_leftover4_starts = leftover_matching_4gram_sites()
    leftover_2_starts = set(leftover_matching_leftover2_starts)
    leftover_3_starts = set(leftover_matching_leftover3_starts)
    leftover_4_starts = set(leftover_matching_leftover4_starts)
    leftover_2_set = set(leftover_remaining_2grams())
    out: list[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]]] = []
    for site, gram4 in zip(extra_sites, parent_4grams, strict=True):
        if site in leftover_2_starts:
            continue
        if site in leftover_3_starts:
            continue
        if site in leftover_4_starts:
            continue
        stems = line_stems_for_site(i_sides, site)
        prev5 = site_prev_5gram_for_4gram(stems, site[2], gram4)
        if prev5 is None:
            continue
        start = prev4_5gram_site(site)
        if start is None:
            continue
        if prev5[:2] in leftover_2_set and prev5[:2] in (GRAM2_076_006, GRAM2_076_011):
            continue
        out.append((prev5, start, "prev", gram4))
    return tuple(out)


