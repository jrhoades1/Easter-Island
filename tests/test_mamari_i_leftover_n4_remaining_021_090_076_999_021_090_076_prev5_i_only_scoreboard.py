def previous_5gram_start_site(
    leftover_site: tuple[str, str, int],
) -> tuple[str, str, int] | None:
    """Previous 5-gram starts three tokens before leftover 090 076."""
    side, line, index = leftover_site
    if index < 3:
        return None
    return (side, line, index - 3)


