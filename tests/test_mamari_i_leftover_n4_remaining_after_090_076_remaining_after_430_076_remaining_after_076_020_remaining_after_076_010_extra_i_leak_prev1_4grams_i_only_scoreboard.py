def leftover_matching_prev4_sites(leftover_sites=None):
    """Previous-4 starts: leftover matching leftover 4-gram start minus one."""
    return leftover_matching_prev1_sites(leftover_sites)


def extra_i_prev1_4grams_at_sites(
    i_sides,
    extra_sites,
    parent_1grams,
    leftover_matching_prev1_starts=None,
    leftover_matching_4gram_starts=None,
):
    """Previous 1-gram plus next three at extra I sites; leftover matching starts excluded."""
    if leftover_matching_prev1_starts is None:
        leftover_matching_prev1_starts = leftover_matching_prev1_sites()
    if leftover_matching_4gram_starts is None:
        leftover_matching_4gram_starts = leftover_matching_4gram_sites()
    leftover_prev1_starts = set(leftover_matching_prev1_starts)
    leftover_4_starts = set(leftover_matching_4gram_starts)
    leftover_4_set = set(CYCLE340_SEQUENCES)
    out = []
    for site, gram1 in zip(extra_sites, parent_1grams, strict=True):
        if site in leftover_prev1_starts:
            continue
        if site in leftover_4_starts:
            continue
        stems = line_stems_for_site(i_sides, site)
        next4 = site_next_4gram_for_1gram(stems, site[2], gram1)
        if next4 is None:
            continue
        if next4 in leftover_4_set:
            continue
        out.append((next4, site, "next", gram1))
    return tuple(out)


def distinct_extra_i_4grams(rows):
    """First-seen distinct extra-I previous-1-gram 4-grams."""
    seen_grams = []
    for gram, _site, _role, _parent in rows:
        if gram not in seen_grams:
            seen_grams.append(gram)
    return tuple(seen_grams)


def leaking_4grams(sequences, n_off_i):
    """Distinct extra-I previous-1-gram 4-grams with N_off_I>0."""
    return tuple(
        gram
        for gram, off in zip(sequences, n_off_i, strict=True)
        if off > 0
    )


