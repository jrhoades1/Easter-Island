def flatten_extra_i_sites_of_leaking_2grams(
    sequences: tuple[tuple[str, ...], ...] = CYCLE349_SEQUENCES,
    extra_each: tuple[tuple[tuple[str, str, int], ...], ...] = CYCLE349_EXTRA_I_SITES,
    leaking: tuple[tuple[str, ...], ...] = CYCLE349_LEAKING,
) -> tuple[tuple[str, str, int], ...]:
    """Flatten extra I I-sites of leaking leftover 2-grams."""
    leak_set = set(leaking)
    return tuple(
        site
        for gram, extra in zip(sequences, extra_each, strict=True)
        if gram in leak_set
        for site in extra
    )


def i_leftover_n4_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_extra_i_leak_2gram_3grams_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    extra_sites: tuple[tuple[str, str, int], ...],
    rows: tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...],
    grams: tuple[tuple[str, ...], ...],
    n_extra_total: int,
    leftover_2grams_still: bool,
    expected_extra_sites: tuple[tuple[str, str, int], ...] = STANDING_EXTRA_I_SITES_FLAT,
    expected_n_extra: int = STANDING_N_EXTRA_I,
    expected_n: int = STANDING_N_DISTINCT_3GRAMS,
) -> bool:
    """True iff extra I=87, complete next 3-grams, all I-only.

    Hapax is not required. Loses if any extra-I 3-gram appears
    off I, if extra_I_total != 87, if an extra-I site is
    line-final so the 3-gram set is empty relative to
    extra_I_total=87, if extra I of leaking leftover 2-grams
    no longer computes, or if leftover 2-grams no longer
    compute. Leftover matching leftover-3-grams of leftover
    4-grams stay nested and do not make the claim lose. Extra
    I of leftover matching leftover-3-grams is not this
    cycle's claim. Extra-I leftover-2-gram 3-grams of I-only
    leftover 2-grams stay nested and are not this population.
    """
    if not leftover_2grams_still:
        return False
    if n_extra_total != expected_n_extra:
        return False
    if extra_sites != expected_extra_sites:
        return False
    if any(gram is None for gram, _site, _role, _parent in rows):
        return False
    if len(grams) != expected_n or len(n_i) != expected_n or len(n_off_i) != expected_n:
        return False
    if any(gram in CYCLE340_SEQUENCES for gram in grams):
        return False
    if not all(
        sequence_is_i_only(on, off)
        for on, off in zip(n_i, n_off_i, strict=True)
    ):
        return False
    return len(rows) == expected_n_extra


