def i_leftover_n4_remaining_090_076_remaining_after_600_remaining_after_020_fwd4_090_076_057_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    n_remaining_next_057: int,
    leftover_sites: tuple[tuple[str, str, int], ...],
    still_computes: bool,
    n_line_final: int,
    forwards: tuple[tuple[str, ...] | None, ...] = STANDING_PER_SITE_FORWARD_4GRAMS,
    sequences: tuple[tuple[str, ...], ...] = STANDING_SEQUENCES,
    expected_n: int = STANDING_N_REMAINING_AFTER_600_REMAINING_AFTER_020_NEXT_057,
    expected_sites: tuple[tuple[str, str, int], ...] = STANDING_LEFTOVER_MATCHING_SITES,
) -> bool:
    """True iff N_next_057=2, leftover sites compute, complete 4-grams, all I-only.

    Hapax is not required. Shared 4th token 600 / N_I=2 does not
    make the claim lose. Empty remainder after peeling 057 does
    not make the claim lose. Extra I does not make the claim lose.
    Loses if any 4-gram appears off I, if N != 2, if a site is
    line-final so the 4-gram set is incomplete relative to N=2,
    or if the two sites no longer compute as leftover n=4 remaining
    remaining-after-021 remaining-after-600 remaining-after-020
    next-057 I 090 076.
    """
    if n_remaining_next_057 != expected_n:
        return False
    if leftover_sites != expected_sites:
        return False
    if not still_computes:
        return False
    if n_line_final != 0:
        return False
    if any(gram is None for gram in forwards):
        return False
    if not sequences:
        return False
    if len(n_i) != len(sequences) or len(n_off_i) != len(sequences):
        return False
    if not continuing_sites_covered(forwards, sequences):
        return False
    return all(
        sequence_is_i_only(on, off)
        for on, off in zip(n_i, n_off_i, strict=True)
    )


