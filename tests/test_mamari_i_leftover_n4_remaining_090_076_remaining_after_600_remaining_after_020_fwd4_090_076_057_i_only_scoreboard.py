def distinct_continuing_forward_4grams(
    forwards: tuple[tuple[str, ...] | None, ...],
) -> tuple[tuple[str, ...], ...]:
    """Distinct continuing leftover next-057 forward 4-grams in first-seen order."""
    seen: set[tuple[str, ...]] = set()
    out: list[tuple[str, ...]] = []
    for gram in forwards:
        if gram is not None and gram not in seen:
            seen.add(gram)
            out.append(gram)
    return tuple(out)


def continuing_sites_covered(
    forwards: tuple[tuple[str, ...] | None, ...],
    sequences: tuple[tuple[str, ...], ...],
) -> bool:
    """True iff every leftover next-057 site that has a 4th token is in sequences."""
    seq_set = set(sequences)
    return all(gram is None or gram in seq_set for gram in forwards)


def leaking_4grams(
    sequences: tuple[tuple[str, ...], ...],
    n_off_i: tuple[int, ...],
) -> tuple[tuple[str, ...], ...]:
    """Distinct continuing 4-grams with N_off_I>0."""
    return tuple(
        gram
        for gram, off in zip(sequences, n_off_i, strict=True)
        if off > 0
    )


def they_share_090_076_057_600(
    forwards: tuple[tuple[str, ...] | None, ...],
    expected: tuple[str, ...] = GRAM4,
) -> bool:
    """True iff every leftover next-057 forward 4-gram is 090 076 057 600."""
