def i_leftover_n4_remaining_021_090_076_remaining_after_999_3gram_090_076_087_i_only(
    i_hits: int,
    off_i_hits: int,
    n_population: int,
    leftover_sites: tuple[tuple[str, str, int], ...],
    still_computes: bool,
    expected_n: int = STANDING_N,
    expected_sites: tuple[tuple[str, str, int], ...] = STANDING_SITES,
) -> bool:
    """True iff I ≥ 1, off-I is 0, N=3, leftover trio still computes.

    Extra I does not make the claim lose. Leftover-extra sites that
    also carry 090 076 087 count as extra I, not as a leak.
    """
    return (
        i_hits >= 1
        and off_i_hits == 0
        and n_population == expected_n
        and leftover_sites == expected_sites
        and still_computes
    )


def leftover_n4_remaining_remaining_after_999_next087_subset(
    leftover_matching: tuple[tuple[str, str, int], ...] = STANDING_LEFTOVER_MATCHING_SITES,
    i_sites: tuple[tuple[str, str, int], ...] = STANDING_I_SITES,
) -> bool:
    """True iff leftover remaining-after-999 next-087 trio ⊆ I 090 076 087."""
    return set(leftover_matching).issubset(set(i_sites))


def extra_i_sites(
    i_sites: tuple[tuple[str, str, int], ...] = STANDING_I_SITES,
    leftover_matching: tuple[tuple[str, str, int], ...] = STANDING_LEFTOVER_MATCHING_SITES,
) -> tuple[tuple[str, str, int], ...]:
    """I 090 076 087 sites that are not leftover remaining-after-999 next-087 trio."""
    leftover_set = set(leftover_matching)
    return tuple(site for site in i_sites if site not in leftover_set)


def named_off_i_sites(
    gram: tuple[str, ...] = GRAM3,
) -> tuple[tuple[str, str, int], ...]:
    """Named (side, line, index) hits on G, S, and T. Search only."""
