def all_matching_4grams_are_090_076_020_010(
    next_4grams: tuple[tuple[str, ...], ...],
    expected: tuple[str, ...] = GRAM4_FORWARD,
) -> bool:
    """True iff every matching next 4-gram is 090 076 020 010."""
    return bool(next_4grams) and all(gram == expected for gram in next_4grams)


def next_020_sites_subset_of_remaining_after_600(
    matching_sites: tuple[tuple[str, str, int], ...],
    remaining: tuple[tuple[str, str, int], ...],
    next_stems_by_site: dict[tuple[str, str, int], str | None],
    stem: str = STANDING_G,
) -> bool:
    """True iff each next-020 site ⊆ remaining-after-600 and has next token 020."""
    remaining_set = set(remaining)
    return all(
        site in remaining_set and next_stems_by_site.get(site) == stem
        for site in matching_sites
    )


def remaining_after_600_still_computes(
    inside_sites: tuple[tuple[str, str, int], ...],
    previous_stems: tuple[str | None, ...],
    remaining: tuple[tuple[str, str, int], ...],
    expected: tuple[tuple[str, str, int], ...] = STANDING_REMAINING_SITES,
) -> bool:
    """True iff the six sites still compute as remaining-after-021 remaining-after-600."""
    computed = leftover_n4_remaining_remaining_after_600(inside_sites, previous_stems)
    after_021 = leftover_n4_remaining_remaining_after_021_without_previous_600(
        inside_sites,
        previous_stems,
    )
    return remaining == computed == after_021 == expected and len(remaining) == 6


def i_leftover_n4_remaining_090_076_remaining_after_600_exactly_4_share_forward_020(
    k: int,
    unique: bool,
    g: str | None,
    n_remaining: int,
    matching: tuple[tuple[str, str, int], ...],
    remaining: tuple[tuple[str, str, int], ...],
    expected: int = HYPOTHESIS_K,
    expected_g: str = STANDING_G,
    expected_remaining: int = STANDING_N_REMAINING_AFTER_600_LOCK,
) -> bool:
    """True iff K_020=4, remaining=6, unique-max still 020, and each next-020 site ⊆ remaining."""
