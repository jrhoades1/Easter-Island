    return (
        k == expected
        and unique
        and g == expected_g
        and n_remaining == expected_remaining
        and len(remaining) == expected_remaining
        and remaining == STANDING_REMAINING_SITES
        and all(site in remaining_set for site in matching)
        and len(matching) == expected
    )


