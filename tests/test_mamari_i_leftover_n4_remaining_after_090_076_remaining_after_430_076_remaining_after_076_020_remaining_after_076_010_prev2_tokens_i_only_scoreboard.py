def leftover_matching_prev2_sites(
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    previous_2grams: tuple[tuple[str, ...] | None, ...] | None = None,
) -> tuple[tuple[str, str, int], ...]:
    """Leftover matching previous-2-gram starts (sites that have two preceding tokens)."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_4gram_sites()
    if previous_2grams is None:
        previous_2grams = leftover_4gram_previous_2grams_tokens()
    return tuple(
        previous_2gram_site(site)
        for site, gram in zip(leftover_sites, previous_2grams, strict=True)
        if gram is not None
    )


def leftover_matching_prev2_sites_each(
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    sequences: tuple[tuple[str, ...], ...] = STANDING_SEQUENCES,
) -> tuple[tuple[tuple[str, str, int], ...], ...]:
    """Per previous 2-gram leftover matching previous-2-gram sites."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_4gram_sites()
    previous_2grams = leftover_4gram_previous_2grams_tokens()
    prev_sites = leftover_matching_prev2_sites(leftover_sites, previous_2grams)
    buckets: dict[tuple[str, ...], list[tuple[str, str, int]]] = {
        gram: [] for gram in sequences
    }
    for gram, site in zip(
        (g for g in previous_2grams if g is not None),
        prev_sites,
        strict=True,
    ):
        buckets[gram].append(site)
    return tuple(tuple(buckets[gram]) for gram in sequences)


