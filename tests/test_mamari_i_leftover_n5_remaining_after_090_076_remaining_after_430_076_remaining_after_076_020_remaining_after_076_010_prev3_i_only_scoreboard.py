def previous_3gram_site(
    leftover_site: tuple[str, str, int],
) -> tuple[str, str, int] | None:
    """Previous 3-gram starts three tokens before leftover 5-gram."""
    side, line, index = leftover_site
    if index < STANDING_N3:
        return None
    return (side, line, index - STANDING_N3)


def leftover_5gram_site_for_prev3(
    site: tuple[str, str, int],
) -> tuple[str, str, int]:
    """Leftover 5-gram starts three tokens after the previous-3 start."""
    side, line, index = site
    return (side, line, index + STANDING_N3)


def leftover_5gram_previous_3grams(
    i_sides: dict | None = None,
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    leftover_5grams: tuple[tuple[str, ...], ...] | None = None,
) -> tuple[tuple[str, ...] | None, ...]:
    """Per leftover matching leftover-5 remaining site, the previous 3-gram or None."""
    if i_sides is None:
        i_sides = load_i_sides()
    if leftover_sites is None:
        leftover_sites = leftover_matching_5gram_sites()
    if leftover_5grams is None:
        leftover_5grams = leftover_remaining_5grams(i_sides=i_sides)
    out: list[tuple[str, ...] | None] = []
    for site, gram in zip(leftover_sites, leftover_5grams, strict=True):
        side, line, index = site
        stems = i_sides[side][IA_LINE_NAMES.index(line)]
        if tuple(stems[index : index + STANDING_N5]) != gram:
            out.append(None)
            continue
        if index >= STANDING_N3:
            out.append(tuple(stems[index - STANDING_N3 : index]))
        else:
            out.append(None)
    return tuple(out)


def leftover_remaining_prev3(
    i_sides: dict | None = None,
) -> tuple[tuple[str, ...], ...]:
    """Previous 3-grams that exist (drops None)."""
    return tuple(gram for gram in leftover_5gram_previous_3grams(i_sides) if gram is not None)


def leftover_matching_prev3_sites(
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    previous_3grams: tuple[tuple[str, ...] | None, ...] | None = None,
) -> tuple[tuple[str, str, int], ...]:
    """Leftover matching previous-3-gram starts (sites that have three preceding tokens)."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_5gram_sites()
    if previous_3grams is None:
        previous_3grams = leftover_5gram_previous_3grams()
    return tuple(
        previous_3gram_site(site)
        for site, gram in zip(leftover_sites, previous_3grams, strict=True)
        if gram is not None
    )


