def leaking_leftover_1grams_with_extra_i(
    sequences=CYCLE358_SEQUENCES,
    extra_each=None,
    leaking=CYCLE358_LEAKING,
):
    """Leaking leftover remaining-after-076-010 1-grams whose extra I is nonempty."""
    if extra_each is None:
        extra_each = tuple(
            extra_i_sites_of_1gram(nge4_sites(gram, load_i_sides()), matching)
            for gram, matching in zip(
                sequences, leftover_matching_1gram_sites_each(), strict=True
            )
        )
    leak_set = set(leaking)
    return tuple(
        gram
        for gram, extra in zip(sequences, extra_each, strict=True)
        if extra and gram in leak_set
    )


