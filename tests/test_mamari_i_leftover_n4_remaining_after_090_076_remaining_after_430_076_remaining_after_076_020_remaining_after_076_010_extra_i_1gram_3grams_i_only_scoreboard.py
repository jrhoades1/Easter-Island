def site_next_3gram_for_1gram(stems, index, gram1):
    """X Y Z if two next stems exist; None at line-final, 1-from-end, or mismatch."""
    if tuple(stems[index : index + len(gram1)]) != gram1:
        return None
    if index + len(gram1) + 1 >= len(stems):
        return None
    return tuple(stems[index : index + len(gram1) + 2])


