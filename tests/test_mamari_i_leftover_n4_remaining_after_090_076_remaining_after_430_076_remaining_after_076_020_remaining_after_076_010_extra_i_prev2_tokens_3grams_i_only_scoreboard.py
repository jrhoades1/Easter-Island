def site_prev_3gram_for_2gram(
    stems: list[str],
    index: int,
    gram2: tuple[str, ...],
) -> tuple[str, ...] | None:
    """X Y Z if the previous token exists; None at line-initial or mismatch."""
    if tuple(stems[index : index + len(gram2)]) != gram2:
        return None
    if index < 1:
        return None
    return tuple(stems[index - 1 : index + len(gram2)])


def prev2_3gram_site(
    extra_site: tuple[str, str, int],
) -> tuple[str, str, int] | None:
    """3-gram starts one token before the extra-I previous-2 start."""
    side, line, index = extra_site
    if index < 1:
        return None
    return (side, line, index - 1)


