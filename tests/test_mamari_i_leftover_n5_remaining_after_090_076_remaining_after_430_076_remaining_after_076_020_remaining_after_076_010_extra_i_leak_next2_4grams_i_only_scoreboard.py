def leftover_matching_next4_sites(
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    i_sides: dict[str, list[list[str]]] | None = None,
) -> tuple[tuple[str, str, int], ...]:
    """Leftover matching next-4 starts: leftover matching leftover-5 next-2 sites with two next tokens."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_5gram_sites()
    if i_sides is None:
        i_sides = load_i_sides()
    next2 = leftover_5gram_next_2grams(i_sides, leftover_sites)
    next2_sites = leftover_matching_next2_sites(leftover_sites, next2)
    out: list[tuple[str, str, int]] = []
    for site, gram2 in zip(next2_sites, (g for g in next2 if g is not None), strict=True):
        stems = line_stems_for_site(i_sides, site)
        if site_next_4gram_for_2gram(stems, site[2], gram2) is not None:
            out.append(site)
    return tuple(out)


def leftover_matching_next4_grams(
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    i_sides: dict[str, list[list[str]]] | None = None,
) -> tuple[tuple[str, ...], ...]:
    """4-grams starting at leftover matching leftover-5 next-2 sites (nested, not this cycle)."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_5gram_sites()
    if i_sides is None:
        i_sides = load_i_sides()
    next2 = leftover_5gram_next_2grams(i_sides, leftover_sites)
    next2_sites = leftover_matching_next2_sites(leftover_sites, next2)
    out: list[tuple[str, ...]] = []
    for site, gram2 in zip(next2_sites, (g for g in next2 if g is not None), strict=True):
        stems = line_stems_for_site(i_sides, site)
        gram4 = site_next_4gram_for_2gram(stems, site[2], gram2)
        if gram4 is not None:
            out.append(gram4)
    return tuple(out)


def extra_i_next2_4grams_at_sites(
    i_sides: dict[str, list[list[str]]],
    extra_sites: tuple[tuple[str, str, int], ...],
    parent_2grams: tuple[tuple[str, ...], ...],
    leftover_matching_next2_starts: tuple[tuple[str, str, int], ...] | None = None,
    leftover_matching_leftover2_starts: tuple[tuple[str, str, int], ...] | None = None,
    leftover_matching_leftover3_starts: tuple[tuple[str, str, int], ...] | None = None,
    leftover_matching_leftover4_starts: tuple[tuple[str, str, int], ...] | None = None,
    leftover_matching_leftover5_starts: tuple[tuple[str, str, int], ...] | None = None,
) -> tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...]:
    """Next 2-gram plus next two tokens at extra I sites; leftover matching starts excluded."""
    if leftover_matching_next2_starts is None:
        leftover_matching_next2_starts = leftover_matching_next2_sites()
    if leftover_matching_leftover2_starts is None:
        leftover_matching_leftover2_starts = leftover_matching_leftover2_of_leftover5()
    if leftover_matching_leftover3_starts is None:
        leftover_matching_leftover3_starts = leftover_matching_leftover3_of_leftover5()
    if leftover_matching_leftover4_starts is None:
        leftover_matching_leftover4_starts = leftover_matching_leftover4_of_leftover5()
    if leftover_matching_leftover5_starts is None:
        leftover_matching_leftover5_starts = leftover_matching_5gram_sites()
    leftover_next2_starts = set(leftover_matching_next2_starts)
    leftover_2_starts = set(leftover_matching_leftover2_starts)
    leftover_3_starts = set(leftover_matching_leftover3_starts)
    leftover_4_starts = set(leftover_matching_leftover4_starts)
    leftover_5_starts = set(leftover_matching_leftover5_starts)
    leftover_2_n4 = set(site for row in leftover_matching_2gram_sites_each() for site in row)
    leftover_3_n4 = set(site for row in leftover_matching_3gram_sites_each() for site in row)
    leftover_4_n4 = set(leftover_matching_4gram_sites())
    leftover_5_set = set(CYCLE414_SEQUENCES)
    leftover_4_set = set(CYCLE340_SEQUENCES)
    out: list[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]]] = []
    for site, gram2 in zip(extra_sites, parent_2grams, strict=True):
        if site in leftover_next2_starts:
            continue
        if site in leftover_2_starts or site in leftover_2_n4:
            continue
        if site in leftover_3_starts or site in leftover_3_n4:
            continue
        if site in leftover_4_starts or site in leftover_4_n4 or site in leftover_5_starts:
            continue
        stems = line_stems_for_site(i_sides, site)
        next4 = site_next_4gram_for_2gram(stems, site[2], gram2)
        if next4 is None:
            continue
        if next4 in leftover_4_set:
            continue
        if any(next4 == gram5[:4] for gram5 in leftover_5_set):
            continue
        out.append((next4, site, "next", gram2))
    return tuple(out)


