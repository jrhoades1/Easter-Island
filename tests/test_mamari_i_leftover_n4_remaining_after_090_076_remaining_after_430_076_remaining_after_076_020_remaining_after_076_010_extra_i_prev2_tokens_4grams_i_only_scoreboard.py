def i_leftover_n4_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_extra_i_prev2_tokens_4grams_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    extra_sites: tuple[tuple[str, str, int], ...],
    rows: tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...],
    grams: tuple[tuple[str, ...], ...],
    n_extra_total: int,
    leftover_prev2_still: bool,
    expected_extra_sites: tuple[tuple[str, str, int], ...] = STANDING_EXTRA_I_SITES_FLAT,
    expected_n_extra: int = STANDING_N_EXTRA_I,
    expected_n: int = STANDING_N_DISTINCT_4GRAMS,
) -> bool:
    """True iff extra I=1, complete previous 4-grams, all I-only.

    Hapax is not required. Loses if any extra-I 4-gram appears
    off I, if extra_I_total != 1, if an extra-I site is
    line-initial so the 4-gram set is incomplete relative to
    extra_I_total=1, if extra I of I-only previous 2-grams with
    extra I no longer computes, or if previous 2-grams no longer
    compute. Leftover matching leftover-3 / leftover-2 /
    previous-4 / previous-3 / previous-2 of leftover 4-grams
    stay nested and do not make the claim lose. Extra I of
    leftover matching leftover-3 / previous-4 / previous-3 /
    previous-2 is not this cycle's claim. Incomplete-set is
    LOSE. Any N_leak>0 is LOSE.
    """
    if not leftover_prev2_still:
        return False
    if n_extra_total != expected_n_extra:
        return False
    if extra_sites != expected_extra_sites:
        return False
    if any(gram is None for gram, _site, _role, _parent in rows):
        return False
    if len(grams) != expected_n or len(n_i) != expected_n or len(n_off_i) != expected_n:
        return False
    if any(gram in CYCLE340_SEQUENCES for gram in grams):
        return False
    if any(gram in CYCLE409_SEQUENCES for gram in grams):
        return False
    if any(gram in CYCLE407_SEQUENCES for gram in grams):
        return False
    if not all(
        sequence_is_i_only(on, off)
        for on, off in zip(n_i, n_off_i, strict=True)
    ):
        return False
    return len(rows) == expected_n_extra


