def i_leftover_n4_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_extra_i_prev3_4grams_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    extra_sites: tuple[tuple[str, str, int], ...],
    rows: tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...],
    grams: tuple[tuple[str, ...], ...],
    n_extra_total: int,
    leftover_prev3_still: bool,
    expected_extra_sites: tuple[tuple[str, str, int], ...] = STANDING_EXTRA_I_SITES_FLAT,
    expected_n_extra: int = STANDING_N_EXTRA_I,
    expected_n: int = STANDING_N_DISTINCT_4GRAMS,
    leftover_matching_prev3_4grams: tuple[tuple[str, ...], ...] = (
        GRAM4_LEFTOVER_MATCHING_PREV3,
    ),
) -> bool:
    """True iff extra I=1 at Ia9[57], complete next 4-grams, all I-only.

    Hapax is not required. Loses if any extra-I 4-gram appears
    off I, if extra_I_total != 1, if the extra-I site is
    line-final so the 4-gram set is empty relative to
    extra_I_total=1, if extra I of previous 3-grams no longer
    computes as Ia9[57], or if previous 3-grams no longer
    compute. Leftover matching previous-3 plus-next 4-grams
    and leftover 4-grams are excluded and do not make the
    claim lose.
    """
    if not leftover_prev3_still:
        return False
    if n_extra_total != expected_n_extra:
        return False
    if extra_sites != expected_extra_sites:
        return False
    if any(gram is None for gram, _site, _role, _parent in rows):
        return False
    if len(grams) != expected_n or len(n_i) != expected_n or len(n_off_i) != expected_n:
        return False
    if any(gram in leftover_matching_prev3_4grams for gram in grams):
        return False
    if any(gram in CYCLE340_SEQUENCES for gram in grams):
        return False
    if not all(
        sequence_is_i_only(on, off)
        for on, off in zip(n_i, n_off_i, strict=True)
    ):
        return False
    return len(rows) == expected_n


