def flatten_extra_i_sites(
    extra_each: tuple[tuple[tuple[str, str, int], ...], ...] = CYCLE347_EXTRA_I_SITES,
) -> tuple[tuple[str, str, int], ...]:
    """Flatten per-previous-3-gram extra I rows into extra-I sites."""
    return tuple(site for row in extra_each for site in row)


def site_next_4gram_for_prev3(
    stems: list[str],
    index: int,
    gram3: tuple[str, ...],
) -> tuple[str, ...] | None:
    """X Y Z W if a next stem exists; None at line-final or mismatch."""
    if tuple(stems[index : index + len(gram3)]) != gram3:
        return None
    if index + len(gram3) >= len(stems):
        return None
    return tuple(stems[index : index + len(gram3) + 1])


def extra_i_prev3_4grams_at_sites(
    i_sides: dict[str, list[list[str]]],
    extra_sites: tuple[tuple[str, str, int], ...],
    parent_3grams: tuple[tuple[str, ...], ...],
    leftover_matching_prev3_4grams: tuple[tuple[str, ...], ...] = (
        GRAM4_LEFTOVER_MATCHING_PREV3,
    ),
) -> tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...]:
    """Previous 3-gram plus next token at extra I sites; leftover matching prev3+next excluded."""
    leftover_prev3_4_set = set(leftover_matching_prev3_4grams)
    leftover_4_set = set(CYCLE340_SEQUENCES)
    leftover_site_set = set(CYCLE340_LEFTOVER_MATCHING)
    leftover_prev3_site_set = set(CYCLE347_MATCHING_PREV3)
    out: list[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]]] = []
    for site, gram3 in zip(extra_sites, parent_3grams, strict=True):
        if site in leftover_site_set or site in leftover_prev3_site_set:
            continue
        stems = line_stems_for_site(i_sides, site)
        next4 = site_next_4gram_for_prev3(stems, site[2], gram3)
        if next4 is None:
            continue
        if next4 in leftover_4_set or next4 in leftover_prev3_4_set:
            continue
        out.append((next4, site, "next", gram3))
    return tuple(out)


def distinct_extra_i_4grams(
    rows: tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...],
) -> tuple[tuple[str, ...], ...]:
    """First-seen distinct extra-I previous-3 4-grams."""
    seen: list[tuple[str, ...]] = []
    for gram, _site, _role, _parent in rows:
        if gram not in seen:
            seen.append(gram)
    return tuple(seen)


def extra_i_sites_of_4gram(
    i_sites: tuple[tuple[str, str, int], ...],
    construction_sites: tuple[tuple[str, str, int], ...] = STANDING_EXTRA_I_SITES_FLAT,
) -> tuple[tuple[str, str, int], ...]:
    """I 4-gram starts outside the extra-I construction sites."""
