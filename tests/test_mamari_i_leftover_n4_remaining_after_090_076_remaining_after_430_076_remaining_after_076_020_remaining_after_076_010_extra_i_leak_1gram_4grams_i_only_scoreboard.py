def site_next_4gram_for_1gram(stems, index, gram1):
    """X Y Z W if three next stems exist; None at line-final, 1-from-end, 2-from-end, or mismatch."""
    if tuple(stems[index : index + len(gram1)]) != gram1:
        return None
    if index + len(gram1) + 2 >= len(stems):
        return None
    return tuple(stems[index : index + len(gram1) + 3])


def extra_i_1gram_4grams_at_sites(
    i_sides,
    extra_sites,
    parent_1grams,
    leftover_matching_1gram_starts=None,
    leftover_matching_4gram_starts=None,
):
    """Leftover 1-gram plus next three at extra I sites; leftover matching leftover-4 excluded."""
    if leftover_matching_1gram_starts is None:
        leftover_matching_1gram_starts = tuple(
            site for row in CYCLE358_MATCHING_EACH for site in row
        )
    if leftover_matching_4gram_starts is None:
        leftover_matching_4gram_starts = CYCLE340_LEFTOVER_MATCHING
    leftover_1_starts = set(leftover_matching_1gram_starts)
    leftover_4_starts = set(leftover_matching_4gram_starts)
    leftover_4_set = set(CYCLE340_SEQUENCES)
    out = []
    for site, gram1 in zip(extra_sites, parent_1grams, strict=True):
        if site in leftover_1_starts:
            continue
        if site in leftover_4_starts:
            continue
        stems = line_stems_for_site(i_sides, site)
        next4 = site_next_4gram_for_1gram(stems, site[2], gram1)
        if next4 is None:
            continue
        if next4 in leftover_4_set:
            continue
        out.append((next4, site, "next", gram1))
    return tuple(out)


