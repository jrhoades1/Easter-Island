def extra_i_sites_of_5gram(
    i_sites: tuple[tuple[str, str, int], ...],
    leftover_matching: tuple[tuple[str, str, int], ...] = STANDING_LEFTOVER_MATCHING_SITES,
) -> tuple[tuple[str, str, int], ...]:
    """I 5-gram sites outside leftover remaining-after-076-010 matching sites."""
    leftover_set = set(leftover_matching)
    return tuple(site for site in i_sites if site not in leftover_set)


def leftover_matching_equals_i_sites(
    leftover_sites: tuple[tuple[str, str, int], ...] = STANDING_LEFTOVER_MATCHING_SITES,
    i_sites: tuple[tuple[tuple[str, str, int], ...], ...] = STANDING_I_SITES,
) -> bool:
    """True iff leftover matching 4-gram sites equal the union of 5-gram I sites."""
    measured = set(site for sites in i_sites for site in sites)
    return set(leftover_sites) == measured


def sequence_is_i_only(n_i: int, n_off_i: int) -> bool:
    """True iff N_I>=1 and N_off_I=0."""
    return n_i >= 1 and n_off_i == 0


def sequence_is_hapax_i_only(n_i: int, n_off_i: int) -> bool:
    """True iff hapax on I (N_I=1) and N_off_I=0."""
    return n_i == 1 and n_off_i == 0


def leaking_5grams(
    sequences: tuple[tuple[str, ...], ...],
    n_off_i: tuple[int, ...],
) -> tuple[tuple[str, ...], ...]:
    """Distinct leftover forward 5-grams with N_off_I>0."""
    return tuple(
        gram
        for gram, off in zip(sequences, n_off_i, strict=True)
        if off > 0
    )


def i_leftover_n4_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_forward_5grams_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    sequences: tuple[tuple[str, ...], ...] = STANDING_SEQUENCES,
    expected_n: int = STANDING_N,
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    next_5grams: tuple[tuple[str, ...] | None, ...] | None = None,
    leftovers: tuple[tuple[tuple[str, ...], int, int, tuple], ...] | None = None,
) -> bool:
    """True iff all 11 leftover remaining-after-076-010 forward 5-grams are I-only.

    Claim holds only if leftover matching sites still compute as
    those 11, every leftover matching site has a next token so
    the 5-gram set is complete relative to N=11, the five leftover
    4-grams still compute, and every forward 5-gram has N_I>=1
    and N_off_I=0. Hapax is not assumed. Nested cycle 343 unique-
    max lose and leftover 4-gram I-only do not make this claim
    lose. Peeling labeled G is not this claim. Extra I is
    recorded, not a lose condition.
    """
    if leftovers is None:
        leftovers = leftover_n4_rows()
    remaining_grams = leftover_remaining_grams(leftovers)
    if leftover_sites is None:
        leftover_sites = leftover_matching_4gram_sites()
    if next_5grams is None:
        next_5grams = leftover_4gram_next_5grams(load_i_sides())
    return (
        remaining_grams == STANDING_LEFTOVER_4GRAMS
        and leftover_sites == STANDING_LEFTOVER_MATCHING_SITES
        and len(leftover_sites) == expected_n
        and len(next_5grams) == expected_n
        and None not in next_5grams
        and tuple(next_5grams) == sequences
        and len(n_i) == expected_n
        and len(n_off_i) == expected_n
        and all(
            sequence_is_i_only(on, off)
            for on, off in zip(n_i, n_off_i, strict=True)
        )
    )


def leftover_forward_5gram_survey_rows(
    sequences: tuple[tuple[str, ...], ...] = STANDING_SEQUENCES,
    i_sites: tuple[tuple[tuple[str, str, int], ...], ...] = STANDING_I_SITES,
    n_i: tuple[int, ...] = STANDING_N_I_EACH,
    n_off_i: tuple[int, ...] = STANDING_N_OFF_I_EACH,
    extra: tuple[tuple[tuple[str, str, int], ...], ...] = STANDING_EXTRA_I_SITES,
    hapax: tuple[bool, ...] = STANDING_HAPAX_EACH,
    hits: tuple[tuple[int, ...], ...] = STANDING_HITS_BY_TABLET,
) -> list[dict]:
    """Survey-shaped per-5-gram rows."""
    rows = []
    for gram, sites, on, off, extra_sites, is_hapax, tablet_hits in zip(
        sequences, i_sites, n_i, n_off_i, extra, hapax, hits, strict=True
    ):
        rows.append(
            {
                "tokens5": list(gram),
                "i_sites": [list(site) for site in sites],
                "leftover_matching_sites": [list(site) for site in sites],
                "N_I": on,
                "N_on_I": on,
                "ia_hits": on,
                "ib_hits": STANDING_IB_HITS,
                "ib_sites": [],
                "N_off_I": off,
                "N_leak": off,
                "off_i_sites": [],
                "extra_i_sites": [list(site) for site in extra_sites],
                "N_extra": len(extra_sites),
                "off_i_tablets": list(OFF_I_TABLETS),
                "off_i_by_tablet": list(STANDING_OFF_I_BY_TABLET),
                "off_i_tablets_with_hits": [],
                "off_i_by_tablet_nonzero": {},
                "vendored_tablets": list(VENDORED_TABLETS),
                "hits_by_tablet": list(tablet_hits),
                "i_only": sequence_is_i_only(on, off),
                "hapax": is_hapax,
            }
        )
    return rows


