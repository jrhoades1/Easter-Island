def leftover_matching_prev4_sites_of_leftover5(
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
) -> tuple[tuple[str, str, int], ...]:
    """Leftover matching previous-4 starts: leftover matching leftover-5 remaining minus four."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_5gram_sites()
    return leftover_matching_prev4_sites(leftover_sites)


def leftover_matching_prev4_grams_of_leftover5(
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    i_sides: dict[str, list[list[str]]] | None = None,
) -> tuple[tuple[str, ...], ...]:
    """4-grams immediately before leftover matching leftover-5 remaining sites (nested)."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_5gram_sites()
    if i_sides is None:
        i_sides = load_i_sides()
    out: list[tuple[str, ...]] = []
    for site in leftover_sites:
        side, line, index = site
        if index < 4:
            continue
        stems = line_stems_for_site(i_sides, site)
        out.append(tuple(stems[index - 4 : index]))
    return tuple(out)


def extra_i_prev2_4grams_at_sites(
    i_sides: dict[str, list[list[str]]],
    extra_sites: tuple[tuple[str, str, int], ...],
    parent_2grams: tuple[tuple[str, ...], ...],
    leftover_matching_prev2_starts: tuple[tuple[str, str, int], ...] | None = None,
    leftover_matching_leftover2_starts: tuple[tuple[str, str, int], ...] | None = None,
    leftover_matching_leftover3_starts: tuple[tuple[str, str, int], ...] | None = None,
    leftover_matching_leftover4_starts: tuple[tuple[str, str, int], ...] | None = None,
    leftover_matching_leftover5_starts: tuple[tuple[str, str, int], ...] | None = None,
) -> tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...]:
    """Two previous tokens plus previous 2-gram at extra I sites; leftover matching starts excluded."""
    if leftover_matching_prev2_starts is None:
        leftover_matching_prev2_starts = leftover_matching_prev2_sites()
    if leftover_matching_leftover2_starts is None:
        leftover_matching_leftover2_starts = leftover_matching_leftover2_of_leftover5()
    if leftover_matching_leftover3_starts is None:
        leftover_matching_leftover3_starts = leftover_matching_leftover3_of_leftover5()
    if leftover_matching_leftover4_starts is None:
        leftover_matching_leftover4_starts = leftover_matching_leftover4_of_leftover5()
    if leftover_matching_leftover5_starts is None:
        leftover_matching_leftover5_starts = leftover_matching_5gram_sites()
    leftover_prev2_starts = set(leftover_matching_prev2_starts)
    leftover_2_starts = set(leftover_matching_leftover2_starts)
    leftover_3_starts = set(leftover_matching_leftover3_starts)
    leftover_4_starts = set(leftover_matching_leftover4_starts)
    leftover_5_starts = set(leftover_matching_leftover5_starts)
    leftover_2_n4 = set(site for row in leftover_matching_2gram_sites_each() for site in row)
    leftover_3_n4 = set(site for row in leftover_matching_3gram_sites_each() for site in row)
    leftover_4_n4 = set(leftover_matching_4gram_sites())
    leftover_5_set = set(CYCLE414_SEQUENCES)
    leftover_4_set = set(CYCLE340_SEQUENCES)
    leftover_3_set = set(leftover_remaining_3grams())
    out: list[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]]] = []
    for site, gram2 in zip(extra_sites, parent_2grams, strict=True):
        if site in leftover_prev2_starts:
            continue
        if site in leftover_2_starts or site in leftover_2_n4:
            continue
        if site in leftover_3_starts or site in leftover_3_n4:
            continue
        if site in leftover_4_starts or site in leftover_4_n4 or site in leftover_5_starts:
            continue
        stems = line_stems_for_site(i_sides, site)
        prev4 = site_prev_4gram_for_2gram(stems, site[2], gram2)
        if prev4 is None:
            continue
        start = prev2_4gram_site(site)
        if start is None:
            continue
        if prev4 in leftover_5_set or prev4 in leftover_4_set or prev4[:3] in leftover_3_set and prev4 in leftover_4_set:
            continue
        out.append((prev4, start, "prev", gram2))
    return tuple(out)


def distinct_extra_i_4grams(
    rows: tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...],
) -> tuple[tuple[str, ...], ...]:
    """First-seen distinct extra-I previous-2-gram 4-grams."""
    seen_grams: list[tuple[str, ...]] = []
    for gram, _site, _role, _parent in rows:
        if gram not in seen_grams:
            seen_grams.append(gram)
    return tuple(seen_grams)


def leaking_4grams(
    sequences: tuple[tuple[str, ...], ...],
    n_off_i: tuple[int, ...],
) -> tuple[tuple[str, ...], ...]:
    """Distinct extra-I previous-2-gram 4-grams with N_off_I>0."""
    return tuple(
        gram
        for gram, off in zip(sequences, n_off_i, strict=True)
        if off > 0
    )


def extra_i_prev2_site_covered_by_4gram(
    extra_site: tuple[str, str, int],
    i_sites: tuple[tuple[str, str, int], ...],
) -> bool:
    """True iff the extra I previous-2-gram site sits inside its extra-I 4-gram."""
    covered = prev2_4gram_site(extra_site)
    return covered is not None and covered in i_sites



def i_leftover_n5_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_extra_i_leak_prev2_4grams_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    extra_sites: tuple[tuple[str, str, int], ...],
    rows: tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...],
    grams: tuple[tuple[str, ...], ...],
    n_extra_total: int,
    leftover_prev2_still: bool,
    n_line_initial: int = STANDING_N_LINE_INITIAL,
    leftover5_remaining_extra: tuple[tuple[str, str, int], ...] = STANDING_LEFTOVER5_REMAINING_EXTRA_I_SITES,
    expected_extra_sites: tuple[tuple[str, str, int], ...] = STANDING_EXTRA_I_SITES_FLAT,
    expected_n_extra: int = STANDING_N_EXTRA_I,
    expected_n: int = STANDING_N_DISTINCT_4GRAMS,
    expected_rows: int = STANDING_N_EXTRA_I_4GRAMS,
) -> bool:
    """True iff extra I=96, complete previous 4-grams, all I-only.

    Hapax is not required. Loses if any extra-I 4-gram appears
    off I, if extra_I_total != 96, if an extra-I site is
    line-initial so the 4-gram set is incomplete relative to
    extra_I_total, if extra I of leaking previous 2-grams with
    extra I no longer computes, or if leftover-5 previous
    2-grams no longer compute. Leftover matching leftover-5
    remaining starts among extra I are excluded as construction
    and do not make the claim lose. Leftover matching leftover-4
    / previous-4 of leftover 5-grams stay nested and do not make
    the claim lose. Extra I of leftover matching leftover-4 /
    previous-4 is not this cycle's claim. Incomplete-set is LOSE.
    Any N_leak>0 is LOSE.
    """
    if not leftover_prev2_still:
        return False
    if n_extra_total != expected_n_extra:
        return False
    if extra_sites != expected_extra_sites:
        return False
    if n_line_initial != 0:
        return False
    if any(site not in extra_sites for site in leftover5_remaining_extra):
        return False
    if any(gram is None for gram, _site, _role, _parent in rows):
        return False
    if len(grams) != expected_n or len(n_i) != expected_n or len(n_off_i) != expected_n:
        return False
    if any(gram in CYCLE414_SEQUENCES for gram in grams):
        return False
    if any(gram in CYCLE340_SEQUENCES for gram in grams):
        return False
    if not all(
        sequence_is_i_only(on, off)
        for on, off in zip(n_i, n_off_i, strict=True)
    ):
        return False
    return len(rows) == expected_rows


