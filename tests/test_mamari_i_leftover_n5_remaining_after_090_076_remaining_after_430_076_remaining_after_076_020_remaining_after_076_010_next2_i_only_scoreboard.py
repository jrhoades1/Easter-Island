def i_leftover_n5_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_next_2grams_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    sequences: tuple[tuple[str, ...], ...] = STANDING_SEQUENCES,
    expected_n: int = STANDING_N,
    leftover_sites: tuple[tuple[str, str, int], ...] | None = None,
    next_2grams: tuple[tuple[str, ...] | None, ...] | None = None,
    leftovers: tuple[tuple[tuple[str, ...], int, int, tuple], ...] | None = None,
    i_sides: dict | None = None,
) -> bool:
    """True iff all leftover remaining-after-076-010 leftover 5-gram next 2-grams are I-only.

    Claim holds only if leftover matching leftover-5 remaining sites
    still compute as those 12, every leftover matching leftover-5
    remaining site has two following tokens so the 2-gram set is
    complete relative to N=12, the twelve leftover 5-grams still
    compute, and every next 2-gram has N_I>=1 and N_off_I=0. Extra
    I does not make the claim lose. Incomplete set is LOSE. Nested
    leftover 5-gram / leftover 5-gram next 1-gram LOSE / leftover
    2-gram LOSE / leftover n=4 next 2-gram LOSE / extra-I leak
    next1 peels do not make this claim lose.
    """
