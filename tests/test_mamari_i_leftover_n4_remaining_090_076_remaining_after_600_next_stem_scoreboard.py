def leftover_n4_remaining_remaining_after_600_next_stems(
    sites: tuple[tuple[str, str, int], ...],
    previous_stems: tuple[str | None, ...],
    next_stems: tuple[str | None, ...],
    locked: tuple[str, ...] = LOCKED_PREVIOUS_STEMS_AFTER_600,
) -> tuple[str, ...]:
    """Next stems of remaining-after-600 sites that have a next token."""
    locked_set = set(locked)
    return tuple(
        nxt
        for prev, nxt in zip(previous_stems, next_stems, strict=True)
        if prev not in locked_set and nxt is not None
    )


def leftover_n4_remaining_remaining_after_600_with_next(
    sites: tuple[tuple[str, str, int], ...],
    previous_stems: tuple[str | None, ...],
    next_stems: tuple[str | None, ...],
    locked: tuple[str, ...] = LOCKED_PREVIOUS_STEMS_AFTER_600,
) -> tuple[tuple[str, str, int], ...]:
    """Remaining-after-600 leftover n=4 remaining sites that have a next token."""
    remaining = leftover_n4_remaining_remaining_after_600(sites, previous_stems, locked)
    rem_next = tuple(
        nxt
        for site, nxt in zip(sites, next_stems, strict=True)
        if site in remaining
    )
    return leftover_sites_with_next(remaining, rem_next)


def leftover_n4_remaining_remaining_after_600_without_next(
    sites: tuple[tuple[str, str, int], ...],
    previous_stems: tuple[str | None, ...],
    next_stems: tuple[str | None, ...],
    locked: tuple[str, ...] = LOCKED_PREVIOUS_STEMS_AFTER_600,
) -> tuple[tuple[str, str, int], ...]:
    """Remaining-after-600 leftover n=4 remaining sites with no next token."""
    remaining = leftover_n4_remaining_remaining_after_600(sites, previous_stems, locked)
    rem_next = tuple(
        nxt
        for site, nxt in zip(sites, next_stems, strict=True)
        if site in remaining
    )
    return leftover_sites_without_next(remaining, rem_next)


def leftover_n4_remaining_remaining_after_600_with_g(
    sites: tuple[tuple[str, str, int], ...],
    previous_stems: tuple[str | None, ...],
    next_stems: tuple[str | None, ...],
    stem: str = STANDING_G,
    locked: tuple[str, ...] = LOCKED_PREVIOUS_STEMS_AFTER_600,
) -> tuple[tuple[str, str, int], ...]:
    """Leftover n=4 remaining remaining-after-600 sites whose next token is G."""
    remaining = set(leftover_n4_remaining_remaining_after_600(sites, previous_stems, locked))
    return tuple(
        site
        for site, nxt in zip(sites, next_stems, strict=True)
        if nxt == stem and site in remaining
    )


def leftover_n4_remaining_remaining_after_600_without_g(
    sites: tuple[tuple[str, str, int], ...],
    previous_stems: tuple[str | None, ...],
    next_stems: tuple[str | None, ...],
    stem: str = STANDING_G,
    locked: tuple[str, ...] = LOCKED_PREVIOUS_STEMS_AFTER_600,
) -> tuple[tuple[str, str, int], ...]:
    """Leftover n=4 remaining remaining-after-600 sites whose next token is not G."""
    remaining = set(leftover_n4_remaining_remaining_after_600(sites, previous_stems, locked))
    return tuple(
        site
        for site, nxt in zip(sites, next_stems, strict=True)
        if nxt is not None and nxt != stem and site in remaining
    )


def remaining_after_600_next_stem_counts(next_stems: tuple[str, ...]) -> Counter:
    """Counts of next stems among leftover n=4 remaining remaining-after-600 with-next."""
    return Counter(next_stems)


def rank_remaining_after_600_next_stems(
    counts: Counter,
) -> tuple[tuple[str, int], ...]:
    """Remaining-after-600 next stems by count, then larger Barthel id."""
    return tuple(
        sorted(
            counts.items(),
            key=lambda item: (-item[1], -barthel_id(item[0])),
        )
    )


def select_remaining_after_600_next_g(
    remaining_stems: tuple[str, ...],
) -> tuple[str | None, int, bool]:
    """Return (G, K, uniquely_most_frequent). Empty remaining-after-600 has no G."""
    ranked = rank_remaining_after_600_next_stems(
        remaining_after_600_next_stem_counts(remaining_stems)
    )
    if not ranked:
        return (None, 0, False)
    gram, count = ranked[0]
    unique = sum(1 for _stem, other in ranked if other == count) == 1
    return (gram, count, unique)


def remaining_after_600_next_stem_frequency_table(
    sites: tuple[tuple[str, str, int], ...],
    previous_stems: tuple[str | None, ...],
    next_stems: tuple[str | None, ...],
    forward_3grams: tuple[tuple[str, ...] | None, ...],
    locked: tuple[str, ...] = LOCKED_PREVIOUS_STEMS_AFTER_600,
) -> tuple[
    tuple[str, int, tuple[tuple[str, str, int], ...], tuple[tuple[str, ...], ...]],
    ...,
]:
    """Remaining-after-600 next-stem frequency: highest count first, then larger id."""
    rem_sites = leftover_n4_remaining_remaining_after_600_with_next(
        sites, previous_stems, next_stems, locked
    )
    rem_stems = leftover_n4_remaining_remaining_after_600_next_stems(
        sites, previous_stems, next_stems, locked
    )
    locked_set = set(locked)
    rem_grams = tuple(
        gram
        for prev, nxt, gram in zip(previous_stems, next_stems, forward_3grams, strict=True)
        if prev not in locked_set and nxt is not None
    )
    first_seen = group_sites_by_next_stem(rem_sites, rem_stems)
    grams_by_stem: dict[str, list[tuple[str, ...]]] = {
        stem: [] for stem, _ in first_seen
    }
    for nxt, gram in zip(rem_stems, rem_grams, strict=True):
        if gram is not None:
            grams_by_stem[nxt].append(gram)
    rows = tuple(
        (stem, len(stem_sites), stem_sites, tuple(grams_by_stem[stem]))
        for stem, stem_sites in first_seen
    )
    return tuple(sorted(rows, key=lambda row: (-row[1], -barthel_id(row[0]))))


