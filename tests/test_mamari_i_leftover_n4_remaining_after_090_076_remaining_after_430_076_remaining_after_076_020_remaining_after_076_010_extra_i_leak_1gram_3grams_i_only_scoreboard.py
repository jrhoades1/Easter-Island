def site_next_3gram_for_1gram(stems, index, gram1):
    """X Y Z if two next stems exist; None at line-final, 1-from-end, or mismatch."""
    if tuple(stems[index : index + len(gram1)]) != gram1:
        return None
    if index + len(gram1) + 1 >= len(stems):
        return None
    return tuple(stems[index : index + len(gram1) + 2])


def extra_i_1gram_3grams_at_sites(
    i_sides,
    extra_sites,
    parent_1grams,
    leftover_matching_1gram_starts=None,
    leftover_matching_3gram_starts=None,
):
    """Leftover 1-gram plus next two at extra I sites; leftover matching starts excluded."""
    if leftover_matching_1gram_starts is None:
        leftover_matching_1gram_starts = tuple(
            site for row in CYCLE358_MATCHING_EACH for site in row
        )
    if leftover_matching_3gram_starts is None:
        leftover_matching_3gram_starts = tuple(
            site for row in leftover_matching_3gram_sites_each() for site in row
        )
    leftover_1_starts = set(leftover_matching_1gram_starts)
    leftover_3_starts = set(leftover_matching_3gram_starts)
    leftover_4_set = set(CYCLE340_SEQUENCES)
    leftover_3_set = set(CYCLE341_SEQUENCES)
    out = []
    for site, gram1 in zip(extra_sites, parent_1grams, strict=True):
        if site in leftover_1_starts:
            continue
        if site in leftover_3_starts:
            continue
        stems = line_stems_for_site(i_sides, site)
        next3 = site_next_3gram_for_1gram(stems, site[2], gram1)
        if next3 is None:
            continue
        if next3 in leftover_4_set:
            continue
        out.append((next3, site, "next", gram1))
    del leftover_3_set
    return tuple(out)


def distinct_extra_i_3grams(rows):
    """First-seen distinct extra-I leftover-1-gram 3-grams."""
    seen_grams = []
    for gram, _site, _role, _parent in rows:
        if gram not in seen_grams:
            seen_grams.append(gram)
    return tuple(seen_grams)


def leaking_3grams(sequences, n_off_i):
    """Distinct extra-I leftover-1-gram 3-grams with N_off_I>0."""
    return tuple(
        gram
        for gram, off in zip(sequences, n_off_i, strict=True)
        if off > 0
    )


