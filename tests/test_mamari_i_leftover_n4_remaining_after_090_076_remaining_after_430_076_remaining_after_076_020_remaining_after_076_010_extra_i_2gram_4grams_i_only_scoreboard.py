def i_leftover_n4_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_extra_i_2gram_4grams_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    extra_sites: tuple[tuple[str, str, int], ...],
    rows: tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...],
    grams: tuple[tuple[str, ...], ...],
    n_extra_total: int,
    leftover_2grams_still: bool,
    expected_extra_sites: tuple[tuple[str, str, int], ...] = STANDING_EXTRA_I_SITES_FLAT,
    expected_n_extra: int = STANDING_N_EXTRA_I,
    expected_n: int = STANDING_N_DISTINCT_4GRAMS,
) -> bool:
    """True iff extra I=29, complete next 4-grams, all I-only.

    Hapax is not required. Loses if any extra-I 4-gram appears
    off I, if extra_I_total != 29, if an extra-I site is
    line-final so the 4-gram set is incomplete relative to
    extra_I_total=29, if extra I of I-only leftover 2-grams
    with extra I no longer computes, or if leftover 2-grams
    no longer compute. Leftover matching leftover 4-grams stay
    nested and do not make the claim lose. Extra I of leftover
    matching leftover 4-grams / leftover matching leftover
    3-grams is not this cycle's claim. Extra-I leftover-2-gram
    3-grams of I-only leftover 2-grams stay nested and are not
    this population. Extra-I leftover-2-gram 4-grams of leaking
    leftover 2-grams stay nested and are not this population.
    """
    if not leftover_2grams_still:
        return False
    if n_extra_total != expected_n_extra:
        return False
    if extra_sites != expected_extra_sites:
        return False
    if any(gram is None for gram, _site, _role, _parent in rows):
        return False
    if len(grams) != expected_n or len(n_i) != expected_n or len(n_off_i) != expected_n:
        return False
    if any(gram in CYCLE340_SEQUENCES for gram in grams):
        return False
    if not all(
        sequence_is_i_only(on, off)
        for on, off in zip(n_i, n_off_i, strict=True)
    ):
        return False
    return len(rows) == expected_n_extra


def extra_i_2gram_4gram_survey_rows(
    sequences: tuple[tuple[str, ...], ...] = STANDING_SEQUENCES,
    parents: tuple[tuple[str, ...], ...] = STANDING_PARENT_2GRAMS,
    extra_sites_each: tuple[tuple[tuple[str, str, int], ...], ...] = STANDING_EXTRA_I_CONSTRUCTION_SITES_EACH,
    i_sites: tuple[tuple[tuple[str, str, int], ...], ...] = STANDING_I_SITES,
    n_i: tuple[int, ...] = STANDING_N_I_EACH,
    n_off_i: tuple[int, ...] = STANDING_N_OFF_I_EACH,
    extra_of_4: tuple[tuple[tuple[str, str, int], ...], ...] = STANDING_EXTRA_I_OF_4GRAMS,
    hapax: tuple[bool, ...] = STANDING_HAPAX_EACH,
    hits: tuple[tuple[int, ...], ...] = STANDING_HITS_BY_TABLET,
) -> list[dict]:
    """Survey-shaped per distinct extra-I leftover-2-gram 4-gram rows."""
    rows = []
    for gram, parent, cons, sites, on, off, extra4, is_hapax, tablet_hits in zip(
        sequences,
        parents,
        extra_sites_each,
        i_sites,
        n_i,
        n_off_i,
        extra_of_4,
        hapax,
        hits,
        strict=True,
    ):
        rows.append(
            {
                "tokens4": list(gram),
                "parent_2gram": list(parent),
                "role": "next",
                "extra_i_2gram_sites": [list(site) for site in cons],
                "extra_i_2gram_site": list(cons[0]),
                "i_sites": [list(site) for site in sites],
                "N_I": on,
                "N_on_I": on,
                "ia_hits": on,
                "ib_hits": STANDING_IB_HITS,
                "ib_sites": [],
                "N_off_I": off,
                "N_leak": off,
                "off_i_sites": [],
                "extra_i_sites": [list(site) for site in extra4],
                "N_extra": len(extra4),
                "off_i_tablets": list(OFF_I_TABLETS),
                "off_i_by_tablet": list(STANDING_OFF_I_BY_TABLET),
                "off_i_tablets_with_hits": [],
                "off_i_by_tablet_nonzero": {},
                "vendored_tablets": list(VENDORED_TABLETS),
                "hits_by_tablet": list(tablet_hits),
                "i_only": sequence_is_i_only(on, off),
                "hapax": is_hapax,
            }
        )
    return rows


