def leftover_remaining_1grams(
    leftovers: tuple[tuple[tuple[str, ...], int, int, tuple], ...] | None = None,
) -> tuple[tuple[str, ...], ...]:
    """Distinct leftover 1-grams of the five remaining-after-076-010 leftover 4-grams."""
    grams4 = leftover_remaining_grams(leftovers)
    seen: list[str] = []
    for gram4 in grams4:
        for tok in gram4:
            if tok not in seen:
                seen.append(tok)
    return tuple((tok,) for tok in seen)


def leftover_matching_1gram_sites_each(
    remaining: tuple[tuple[tuple[str, ...], int, int, tuple], ...] | None = None,
) -> tuple[tuple[tuple[str, str, int], ...], ...]:
    """Leftover-derived 1-gram starts: token offsets at leftover 4-gram sites."""
    if remaining is None:
        remaining = leftover_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010()
    tokens = leftover_remaining_1grams()
    buckets: dict[str, list[tuple[str, str, int]]] = {tok[0]: [] for tok in tokens}
    for gram4, _n, _f, sites in remaining:
        for side, line, index in sites:
            for offset, tok in enumerate(gram4):
                buckets[tok].append((side, line, index + offset))
    return tuple(tuple(buckets[tok[0]]) for tok in tokens)


def extra_i_sites_of_1gram(
    i_sites: tuple[tuple[str, str, int], ...],
    leftover_matching: tuple[tuple[str, str, int], ...],
) -> tuple[tuple[str, str, int], ...]:
    """I 1-gram sites outside leftover-derived 1-gram starts of the five leftovers."""
    leftover_set = set(leftover_matching)
    return tuple(site for site in i_sites if site not in leftover_set)


