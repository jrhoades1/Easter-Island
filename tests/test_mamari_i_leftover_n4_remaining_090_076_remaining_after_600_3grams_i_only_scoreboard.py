def remaining_after_600_3grams(
    remaining_stems: tuple[str, ...] = STANDING_REMAINING_PREVIOUS_STEMS,
) -> tuple[tuple[str, ...], ...]:
    """3-grams W 090 076 for leftover n=4 remaining remaining-after-600 previous stems."""
    return tuple((stem, "090", "076") for stem in remaining_stems)


def leftover_n4_remaining_090_076_site_for_3gram(
    site: tuple[str, str, int],
) -> tuple[str, str, int]:
    """090 076 starts one token after W 090 076."""
    side, line, index = site
    return (side, line, index + 1)


def leftover_n4_remaining_remaining_after_600_3gram_sites(
    leftover_matching: tuple[tuple[str, str, int], ...],
) -> tuple[tuple[str, str, int], ...]:
    """Leftover n=4 remaining remaining-after-600 090-starts shifted to W-starts."""
    return tuple((side, line, index - 1) for side, line, index in leftover_matching)


def sequence_is_i_only(n_i: int, n_off_i: int) -> bool:
    """True iff N_I>=1 and N_off_I=0."""
    return n_i >= 1 and n_off_i == 0


def i_leftover_n4_remaining_090_076_remaining_after_600_3grams_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    n_remaining: int,
    remaining_sites: tuple[tuple[str, str, int], ...],
    expected_n: int = STANDING_N_REMAINING_AFTER_600_LOCK,
    expected_sites: tuple[tuple[str, str, int], ...] = STANDING_REMAINING_SITES,
) -> bool:
    """True iff remaining-after-600 N=6 and every previous 3-gram is I-only.

    Extra I does not make the claim lose. Loses if any 3-gram
    appears off I, if N_remaining_after_600 != 6, or if the six
    sites no longer compute as remaining-after-600 leftover n=4
    remaining I 090 076. A cycle 272/274 T leak is a genuine
    LOSE; do not drop those sites.
    """
    return (
        n_remaining == expected_n
        and remaining_sites == expected_sites
        and len(n_i) == expected_n
        and len(n_off_i) == expected_n
        and all(
            sequence_is_i_only(on, off)
            for on, off in zip(n_i, n_off_i, strict=True)
        )
    )


def leftover_n4_remaining_remaining_after_600_3gram_subset(
    leftover_site: tuple[str, str, int],
    i_sites: tuple[tuple[str, str, int], ...],
) -> bool:
    """True iff leftover n=4 remaining remaining-after-600 W-start ⊆ I W 090 076."""
    return leftover_n4_remaining_remaining_after_600_3gram_sites((leftover_site,))[0] in i_sites


def leftover_n4_remaining_remaining_after_600_3grams_subset_all(
    leftover_sites: tuple[tuple[str, str, int], ...],
    i_sites_each: tuple[tuple[tuple[str, str, int], ...], ...],
) -> bool:
    """True iff every remaining-after-600 site sits in its I 3-gram sites."""
    if len(leftover_sites) != len(i_sites_each):
        return False
    return all(
        leftover_n4_remaining_remaining_after_600_3gram_subset(site, sites)
        for site, sites in zip(leftover_sites, i_sites_each, strict=True)
    )


def extra_i_sites(
    i_sites: tuple[tuple[str, str, int], ...],
    leftover_matching: tuple[tuple[str, str, int], ...],
) -> tuple[tuple[str, str, int], ...]:
    """I W 090 076 sites that are not leftover n=4 remaining remaining-after-600."""
    leftover_set = set(leftover_matching)
    return tuple(
        site
        for site in i_sites
        if leftover_n4_remaining_090_076_site_for_3gram(site) not in leftover_set
    )


def site_next_4gram_for_3gram(
    stems: list[str],
    index: int,
    gram3: tuple[str, ...],
) -> tuple[str, ...] | None:
    """W 090 076 Y if a following stem exists; None at end-of-line."""
    if tuple(stems[index : index + len(gram3)]) != gram3:
        return None
    if index + len(gram3) >= len(stems):
        return None
    return tuple(stems[index : index + len(gram3) + 1])


