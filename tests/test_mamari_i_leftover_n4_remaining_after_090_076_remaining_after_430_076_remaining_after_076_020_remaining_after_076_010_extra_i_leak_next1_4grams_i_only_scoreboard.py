def leftover_matching_next4_sites(
    leftover_sites=None,
    i_sides=None,
):
    """Leftover matching next-4 starts: leftover matching next-1 sites with next-three."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_4gram_sites()
    if i_sides is None:
        i_sides = load_i_sides()
    out = []
    for site in leftover_matching_next1_sites(leftover_sites):
        stems = line_stems_for_site(i_sides, site)
        parent = (stems[site[2]],) if site[2] < len(stems) else ()
        if site_next_4gram_for_1gram(stems, site[2], parent) is not None:
            out.append(site)
    return tuple(out)


def leftover_matching_next4_grams(
    leftover_sites=None,
    i_sides=None,
):
    """4-grams starting at leftover matching next-1 sites (nested, not this cycle)."""
    if leftover_sites is None:
        leftover_sites = leftover_matching_4gram_sites()
    if i_sides is None:
        i_sides = load_i_sides()
    out = []
    for site in leftover_matching_next1_sites(leftover_sites):
        stems = line_stems_for_site(i_sides, site)
        parent = (stems[site[2]],) if site[2] < len(stems) else ()
        gram4 = site_next_4gram_for_1gram(stems, site[2], parent)
        if gram4 is not None:
            out.append(gram4)
    return tuple(out)


def extra_i_next1_4grams_at_sites(
    i_sides,
    extra_sites,
    parent_1grams,
    leftover_matching_next1_starts=None,
    leftover_matching_leftover2_starts=None,
    leftover_matching_leftover3_starts=None,
    leftover_matching_leftover4_starts=None,
):
    """Next 1-gram plus next three at extra I sites; leftover matching starts excluded."""
    if leftover_matching_next1_starts is None:
        leftover_matching_next1_starts = leftover_matching_next1_sites()
    if leftover_matching_leftover2_starts is None:
        leftover_matching_leftover2_starts = tuple(
            site for row in leftover_matching_2gram_sites_each() for site in row
        )
    if leftover_matching_leftover3_starts is None:
        leftover_matching_leftover3_starts = tuple(
            site for row in leftover_matching_3gram_sites_each() for site in row
        )
    if leftover_matching_leftover4_starts is None:
        leftover_matching_leftover4_starts = leftover_matching_4gram_sites()
    leftover_next1_starts = set(leftover_matching_next1_starts)
    leftover_2_starts = set(leftover_matching_leftover2_starts)
    leftover_3_starts = set(leftover_matching_leftover3_starts)
    leftover_4_starts = set(leftover_matching_leftover4_starts)
    leftover_4_set = set(CYCLE340_SEQUENCES)
    out = []
    for site, gram1 in zip(extra_sites, parent_1grams, strict=True):
        if site in leftover_next1_starts:
            continue
        if site in leftover_2_starts:
            continue
        if site in leftover_3_starts:
            continue
        if site in leftover_4_starts:
            continue
        stems = line_stems_for_site(i_sides, site)
        next4 = site_next_4gram_for_1gram(stems, site[2], gram1)
        if next4 is None:
            continue
        if next4 in leftover_4_set:
            continue
        out.append((next4, site, "next", gram1))
    return tuple(out)


def distinct_extra_i_4grams(rows):
    """First-seen distinct extra-I next-1-gram 4-grams."""
    seen_grams = []
    for gram, _site, _role, _parent in rows:
        if gram not in seen_grams:
            seen_grams.append(gram)
    return tuple(seen_grams)


def leaking_4grams(sequences, n_off_i):
    """Distinct extra-I leaking next-1-gram 4-grams with N_off_I>0."""
    return tuple(
        gram
        for gram, off in zip(sequences, n_off_i, strict=True)
        if off > 0
    )


def i_leftover_n4_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_extra_i_leak_next1_4grams_all_i_only(
    n_i,
    n_off_i,
    extra_sites,
    rows,
    grams,
    n_extra_total,
    leftover_next1_still,
    expected_extra_sites=None,
    expected_n_extra=None,
    expected_n=None,
):
    """True iff extra I=771, complete next 4-grams, all I-only.

    Hapax is not required. Loses if any extra-I 4-gram appears
    off I, if extra_I_total != 771, if an extra-I site is
    line-final or 1-from-end or 2-from-end so the 4-gram set
    is incomplete relative to extra_I_total=771, if leftover
    matching leftover-2 / leftover-3 / leftover-4 starts are
    excluded so the set is incomplete, if extra I of leaking
    next 1-grams no longer computes, or if next 1-grams no
    longer compute. Leftover matching leftover-4 / next-4 of
    leftover 4-grams stay nested and do not make the claim
    lose by themselves. Extra I of leftover matching leftover-4
    / next-4 is not this cycle's claim. Incomplete-set is LOSE.
    Any N_leak>0 is LOSE.
    """
    if expected_extra_sites is None:
        expected_extra_sites = STANDING_EXTRA_I_SITES_FLAT
    if expected_n_extra is None:
        expected_n_extra = STANDING_N_EXTRA_I
    if expected_n is None:
        expected_n = STANDING_N_DISTINCT_4GRAMS
    if not leftover_next1_still:
        return False
    if n_extra_total != expected_n_extra:
        return False
    if extra_sites != expected_extra_sites:
        return False
    if any(gram is None for gram, _site, _role, _parent in rows):
        return False
    if len(grams) != expected_n or len(n_i) != expected_n or len(n_off_i) != expected_n:
        return False
    if any(gram in CYCLE340_SEQUENCES for gram in grams):
        return False
    if not all(
        sequence_is_i_only(on, off)
        for on, off in zip(n_i, n_off_i, strict=True)
    ):
        return False
    return len(rows) == expected_n_extra


