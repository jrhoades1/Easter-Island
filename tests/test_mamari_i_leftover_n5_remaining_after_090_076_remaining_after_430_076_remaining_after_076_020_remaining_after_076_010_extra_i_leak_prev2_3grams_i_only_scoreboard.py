def i_leftover_n5_remaining_after_090_076_remaining_after_430_076_remaining_after_076_020_remaining_after_076_010_extra_i_leak_prev2_3grams_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    extra_sites: tuple[tuple[str, str, int], ...],
    rows: tuple[tuple[tuple[str, ...], tuple[str, str, int], str, tuple[str, ...]], ...],
    grams: tuple[tuple[str, ...], ...],
    n_extra_total: int,
    leftover_prev2_still: bool,
    n_line_initial: int = STANDING_N_LINE_INITIAL,
    leftover5_remaining_extra: tuple[tuple[str, str, int], ...] = STANDING_LEFTOVER5_REMAINING_EXTRA_I_SITES,
    expected_extra_sites: tuple[tuple[str, str, int], ...] = STANDING_EXTRA_I_SITES_FLAT,
    expected_n_extra: int = STANDING_N_EXTRA_I,
    expected_n: int = STANDING_N_DISTINCT_3GRAMS,
    expected_rows: int = STANDING_N_EXTRA_I_3GRAMS,
) -> bool:
    """True iff extra I=96, complete previous 3-grams, all I-only.

    Hapax is not required. Loses if any extra-I 3-gram appears
    off I, if extra_I_total != 96, if an extra-I site is
    line-initial so the 3-gram set is incomplete relative to
    extra_I_total, if extra I of leaking previous 2-grams with
    extra I no longer computes, or if leftover-5 previous
    2-grams no longer compute. Leftover matching leftover-5
    remaining starts among extra I are excluded as construction
    and do not make the claim lose. Leftover matching leftover-3
    / previous-3 of leftover 5-grams stay nested and do not make
    the claim lose. Extra I of leftover matching leftover-3 /
    previous-3 is not this cycle's claim. Incomplete-set is LOSE.
    Any N_leak>0 is LOSE.
    """
    if not leftover_prev2_still:
        return False
    if n_extra_total != expected_n_extra:
        return False
    if extra_sites != expected_extra_sites:
        return False
    if n_line_initial != 0:
        return False
    if any(site not in extra_sites for site in leftover5_remaining_extra):
        return False
    if any(gram is None for gram, _site, _role, _parent in rows):
        return False
    if len(grams) != expected_n or len(n_i) != expected_n or len(n_off_i) != expected_n:
        return False
    if any(gram in CYCLE414_SEQUENCES for gram in grams):
        return False
    if any(gram in CYCLE340_SEQUENCES for gram in grams):
        return False
    if not all(
        sequence_is_i_only(on, off)
        for on, off in zip(n_i, n_off_i, strict=True)
    ):
        return False
    return len(rows) == expected_rows


