def i_leftover_n4_remaining_090_076_remaining_after_600_extra_i_prev4_all_i_only(
    n_i: tuple[int, ...],
    n_off_i: tuple[int, ...],
    extra_sites: tuple[tuple[str, str, int], ...],
    per_site_4grams: tuple[tuple[str, ...] | None, ...],
    i_sites_each: tuple[tuple[tuple[str, str, int], ...], ...],
    grams: tuple[tuple[str, ...], ...],
    n_extra_total: int,
    n_remaining: int,
    remaining_sites: tuple[tuple[str, str, int], ...],
    expected_extra_sites: tuple[tuple[str, str, int], ...] = STANDING_EXTRA_I_SITES,
    expected_n_extra: int = STANDING_N_EXTRA_I,
    expected_n: int = STANDING_N_DISTINCT_4GRAMS,
    expected_remaining: int = STANDING_N_REMAINING_AFTER_600_LOCK,
    expected_remaining_sites: tuple[tuple[str, str, int], ...] = STANDING_REMAINING_SITES,
) -> bool:
    """True iff extra_I_total=2 at Ia5[65]/Ia13[134], complete 4-grams, all I-only.

    Hapax is not required. Loses if any extra-I 4-gram appears
    off I, if extra_I_total != 2, if the extra-I set is empty
    when extra I of 000/008 is not 0, if an extra I site is
    line-initial so the 4-gram set is empty relative to
    extra_I_total=2, or if remaining-after-600 no longer
    computes as the six leftover n=4 remaining sites.
    Vacuous HOLD on extra I=0 is a fail.
    """
    if n_remaining != expected_remaining:
        return False
    if remaining_sites != expected_remaining_sites:
        return False
    if n_extra_total != expected_n_extra:
        return False
    if extra_sites != expected_extra_sites:
        return False
    if n_extra_total == 0:
        return False
    if any(gram is None for gram in per_site_4grams):
        return False
    if len(grams) != expected_n or len(n_i) != expected_n or len(n_off_i) != expected_n:
        return False
    if not all(
        sequence_is_i_only(on, off)
        for on, off in zip(n_i, n_off_i, strict=True)
    ):
        return False
    return extra_i_sites_covered_by_4grams(
        extra_sites,
        per_site_4grams,
        i_sites_each,
        grams,
    )


