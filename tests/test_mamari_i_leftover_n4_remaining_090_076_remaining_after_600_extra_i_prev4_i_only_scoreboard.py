def leftover_n4_remaining_remaining_after_600_i_only_extra_i_each(
    extra_each: tuple[tuple[tuple[str, str, int], ...], ...] = CYCLE310_EXTRA_I_SITES_EACH,
    remaining_stems: tuple[str, ...] = CYCLE308_REMAINING_PREVIOUS_STEMS,
    n_i: tuple[int, ...] = CYCLE310_N_I_EACH,
    n_off_i: tuple[int, ...] = CYCLE310_N_OFF_I_EACH,
    excluded_stem: str = STANDING_EXCLUDED_PREVIOUS_999_STEM,
) -> tuple[tuple[tuple[str, str, int], ...], ...]:
    """Per I-only remaining-after-600 3-gram extra I, excluding leftover extra previous-999."""
    rows: list[tuple[tuple[str, str, int], ...]] = []
    for extra, stem, on, off in zip(
        extra_each, remaining_stems, n_i, n_off_i, strict=True
    ):
        if not sequence_is_i_only(on, off):
            continue
        if stem == excluded_stem:
            continue
        if extra:
            rows.append(extra)
    return tuple(rows)


